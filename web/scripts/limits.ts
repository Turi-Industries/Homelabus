// Writes `src/lib/api/limits.ts`: for every field of every schema, the bounds the
// controller declares — longest text, smallest and largest number — read from
// `openapi.json`.
//
// Generated rather than written down: a field's `maxlength` or `max` is the number the
// controller refuses past (`hlb-controller/src/limits.rs`), so the two cannot disagree.
import { readFileSync, writeFileSync } from 'node:fs';

type Property = { maxLength?: number; minimum?: number; maximum?: number };
const document = JSON.parse(readFileSync('openapi.json', 'utf8')) as {
	components: { schemas: Record<string, { properties?: Record<string, Property> }> };
};

const table: Record<string, Record<string, Property>> = {};
for (const [name, schema] of Object.entries(document.components.schemas)) {
	for (const [field, p] of Object.entries(schema.properties ?? {})) {
		// A bound only `u64` implies (a minimum of 0) is not a declaration about the field.
		if (p.maxLength === undefined && p.maximum === undefined) continue;
		const bound: Property = {};
		if (p.maxLength !== undefined) bound.maxLength = p.maxLength;
		if (p.minimum !== undefined) bound.minimum = p.minimum;
		if (p.maximum !== undefined) bound.maximum = p.maximum;
		(table[name] ??= {})[field] = bound;
	}
}

writeFileSync(
	'src/lib/api/limits.ts',
	'// Generated by `scripts/limits.ts` from `openapi.json`. Do not edit.\n' +
		`export const limits = ${JSON.stringify(table, null, '\t')} as const;\n`
);
