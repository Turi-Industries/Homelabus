// Writes `src/lib/api/requires.ts`: for every route, the right the controller requires,
// read from the `x-hlb-requires` and `x-hlb-public` extensions of `openapi.json`.
//
// Generated rather than written down: which page and which button to offer is decided
// from the same declarations the controller enforces, so the two cannot disagree.
import { readFileSync, writeFileSync } from 'node:fs';

type Operation = { 'x-hlb-requires'?: string; 'x-hlb-public'?: boolean };
const document = JSON.parse(readFileSync('openapi.json', 'utf8')) as {
	paths: Record<string, Record<string, Operation>>;
};

const table: Record<string, Record<string, string>> = {};
for (const [path, operations] of Object.entries(document.paths)) {
	for (const [method, operation] of Object.entries(operations)) {
		const right = operation['x-hlb-public'] ? 'public' : operation['x-hlb-requires'];
		if (right === undefined) throw new Error(`${method.toUpperCase()} ${path} declares no right`);
		(table[path] ??= {})[method.toUpperCase()] = right.replaceAll('-', '_');
	}
}

writeFileSync(
	'src/lib/api/requires.ts',
	'// Generated by `scripts/requires.ts` from `openapi.json`. Do not edit.\n' +
		`export const requires = ${JSON.stringify(table, null, '\t')} as const;\n`
);
