#!/usr/bin/env bash
#
# The project's goals, each as a number read from the repository — what `/improve`
# starts from, and what it must move.
#
#   1. Deploy on any machine, as easily and as fast as possible.
#   2. Never lose data.
#   3. Never have it stolen, and trust nobody: no provider, everything encrypted.
#   4. Add an app to the catalog without touching Rust.
#   5. Always available: the vital apps reachable while the house is down.
#   6. Always up to date, without breaking.
#   7. Simple and beautiful for whoever runs it — never at the households' expense.
#
# A measure the repository cannot answer is printed UNMEASURED with the probe that would
# answer it, rather than left out: a scorecard that only shows what is easy to count
# says everything is fine. Building one of those probes is a legitimate improvement.
#
# 🔴 Do not edit this file in the change that claims to move one of its numbers. A
# number moved by changing how it is counted is not progress (ImpossibleBench, 2025:
# models given a failing check edit the check). Change the measure in its own commit,
# saying why the old one was wrong.
#
# Usage: scripts/scorecard.sh   (from anywhere in the repository; `gh` optional)

set -uo pipefail
cd "$(git rev-parse --show-toplevel)" || exit 1

row() { printf '| %s | %s | %s | %s |\n' "$1" "$2" "$3" "$4"; }

# The newest figure a drill wrote to docs/measures.tsv, with the release it was measured
# on, and saying so when a newer release has come since: a figure that stops being
# measured must not go on reading as today's. Prints nothing for a measure with no row.
measured() {
    local row value hlb date
    row=$(awk -F'\t' -v m="$1" '$3 == m { line = $4 "\t" $2 "\t" $1 } END { if (line != "") print line }' docs/measures.tsv 2>/dev/null)
    [[ -n $row ]] || return 0
    IFS=$'\t' read -r value hlb date <<<"$row"
    printf '%s (hlb %s, %s)' "$value" "$hlb" "$date"
    # A build between two releases is no older than the newest one: 0.4.5-dev after 0.4.4.
    if [[ -n ${tag:-} && $(printf '%s\n%s\n' "${hlb%-dev}" "${tag#v}" | sort -V | head -1) != "${tag#v}" ]]; then
        printf ' — STALE, the newest release is %s' "${tag#v}"
    fi
}

# 1. Deploy -------------------------------------------------------------------------
tag=$(git describe --tags --abbrev=0 2>/dev/null)
if [[ -z $tag ]]; then
    binary="no tag"
elif ! command -v gh >/dev/null; then
    binary="unknown (no gh)"
elif assets=$(gh release view "$tag" --json assets -q '[.assets[].name] | join(", ")' 2>/dev/null); then
    binary="$tag: ${assets:-a release with no assets}"
else
    binary="$tag: no release"
fi
row "1 deploy" "\`hlb\` downloadable for the newest tag, without a Rust toolchain" "$binary" "a static binary per architecture, checksummed and signed"
# Seconds, with the path they measure: `scripts/drills/deploy.sh` writes all three.
first_app=$(measured deploy-first-app-seconds)
if [[ -n $first_app ]]; then
    row "1 deploy" "seconds from a bare machine to the first app" "netinst $(measured deploy-os-seconds); then to an app with no dependency $first_app; to one with a database and sign-in $(measured deploy-full-app-seconds)" "measured each release, and falling"
else
    row "1 deploy" "seconds from a bare machine to the first app" "UNMEASURED — probe: \`scripts/drills/deploy.sh\`" "measured each release, and falling"
fi

# 2. Never lose ----------------------------------------------------------------------
# Not here: "volumes with `backup: false`" — all twelve carry their reason, often in a
# comment above the list item, and counting comments by distance reported seven
# false alarms on its first run (2026-10-27).
# Proves the packaging on a CI runner, never a house's own data: the row after it does.
quality=$(curl -fsS -m 10 https://turi-industries.github.io/homelabus-catalog/quality-v1.json 2>/dev/null |
    jq -r '[.apps[].last] | "\(map(select(.restore == "passed")) | length) of \(length), on hlb \(map(.hlb) | max), newest \(map(.date) | max)"' 2>/dev/null)
row "2 never lose" "apps whose restore passed in the catalog's CI" "${quality:-unknown (no network, or no jq)}" "every app with data, each week"
restores=$(measured restores-read-back)
row "2 never lose" "apps whose backups were read back and read good on the lab in the last 30 days: restored and counted, never started" "${restores:-UNMEASURED — probe: \`scripts/drills/restores.sh\`}" "every app with data, weekly, alerting when one fails"
started=$(measured recovery-started)
row "2 never lose" "apps started on their restored copy on a bare machine, from the kit and one destination alone, every assertion read good" "${started:-UNMEASURED — probe: \`scripts/drills/recovery.sh\`}" "every app with data, each release"

# 3. Never stolen --------------------------------------------------------------------
# Not here: images without a digest — `catalog validate` refuses them already, and the
# two lines a grep finds are the image built here and a YAML alias.
unpinned=$(grep -rhE '^\s*-?\s*uses:' .github/workflows | grep -vcE '@[0-9a-f]{40}')
row "3 never stolen" "CI actions not pinned by commit" "$unpinned" "0"
ignored=$(grep -cE '"RUSTSEC-' .cargo/audit.toml 2>/dev/null || echo 0)
row "3 never stolen" "advisories ignored by \`cargo audit\`" "$ignored (each with its reason)" "only with a reason that holds"
# The signature's own file, beside the release's: what `install.sh` checks first.
if [[ $binary == *SHA256SUMS.sigstore.json* ]]; then
    signed="$tag: \`SHA256SUMS\` signed by cosign"
else
    signed="${tag:-no tag}: no signature published"
fi
row "3 never stolen" "releases signed, with a verifiable provenance" "$signed" "every artifact"
# By `hlb_types::binding::carries_secret`. Once at zero `catalog validate` refuses one —
# the gate holds the catalog to it, so the refusal being there IS the zero; until then,
# the count `hlb-catalog/tests/secrets_as_files.rs` holds equal to the catalog's.
if grep -q 'hands a secret through the environment' crates/hlb-catalog/src/lib.rs; then
    in_env="0, refused by \`catalog validate\`"
else
    in_env=$(grep -sohE 'STILL_IN_AN_ENVIRONMENT: usize = [0-9]+' crates/hlb-catalog/tests/secrets_as_files.rs | grep -oE '[0-9]+$')
fi
row "3 never stolen" "catalog variables handing a container a secret through its environment" "${in_env:-UNMEASURED — the test holding the count is gone}" "0: \`docker inspect\` shows no secret"
# A fact of each machine, not of the repository: the cluster says it, the code cannot.
levels=$(measured node-levels)
row "3 never stolen" "nodes per protection level (A verified boot … D a virtual machine)" "${levels:-UNMEASURED — probe: \`scripts/drills/stolen.sh\`} — the lab only: its virtual machines read D by design, so this moves on real hardware alone" "every manager and the controller's node at A or B"
no_tang=$(measured stolen-enc2-no-tang)
if [[ -n $no_tang ]]; then
    gives_up="no Tang, level B: $no_tang; no Tang, level A: $(measured stolen-enc3-no-tang); another TPM: $(measured stolen-enc2-other-tpm)"
else
    gives_up="UNMEASURED — probe: \`scripts/drills/stolen.sh\`"
fi
row "3 never stolen" "what a node taken away from the lab gives up" "$gives_up" "closed, each time"

# 4. An app without Rust -------------------------------------------------------------
# An app enters by a pull request to `homelabus-catalog`, mounted at `catalog/apps`: no
# commit there can carry Rust, so what this counts is the apps that came that way. A
# schema field one of them needed is a Homelabus commit before it, and shows in phase
# 3's other measures, not here. The catalog's history began as one commit (2026-11-02)
# holding every app then: those are said apart.
if [[ -d catalog/apps/.git || -f catalog/apps/.git ]]; then
    root=$(git -C catalog/apps rev-list --max-parents=0 HEAD | tail -1)
    apps=0
    before=0
    for manifest in catalog/apps/*/manifest.yaml; do
        added=$(git -C catalog/apps log --diff-filter=A --format=%H -- "${manifest#catalog/apps/}" | tail -1)
        [[ -n $added ]] || continue
        if [[ $added == "$root" ]]; then
            before=$((before + 1))
        else
            apps=$((apps + 1))
        fi
    done
    added_apps="$apps added through \`homelabus-catalog\` ($before predate it, uncounted)"
else
    added_apps="UNMEASURED — \`catalog/apps\` is not checked out: \`git submodule update --init\`"
fi
row "4 no Rust" "apps that entered by a pull request to the catalog, which holds no Rust" "$added_apps" "every app added from now on"

# Phase 3's gate: an app reaching the house with no release means the house reads an
# index the owner signs, not only the catalog its binary carries.
if grep -q 'pub const OFFICIAL_KEY: Option<&str> = None;' crates/hlb-catalog/src/lib.rs; then
    catalog="0 — no official key compiled in (\`hlb_catalog::OFFICIAL_KEY\`): a house reads the catalog its hlb carries, and a new app needs a release"
else
    catalog="the official index is read — probe: a pull request to \`homelabus-catalog\` installed on the lab"
fi
row "4 no Rust" "apps that reached an installed house through a catalog pull request, with no \`hlb\` release" "$catalog" "every app, once its index is signed"

# 5. Always available ---------------------------------------------------------------
row "5 available" "minutes until the vital apps answer from the VPS, the house cut" "UNMEASURED — probe: the lab's moving-house drill; no site, relay or lifeboat exists" "measured each release"

# 6. Up to date ----------------------------------------------------------------------
# Every update and not a fix's: which is one needs the CVE data of phase 5. And nothing
# applies by itself yet, so it says how long a person took.
lag=$(measured updates-lag)
row "6 up to date" "days from an update first seen to applied, on the lab: EVERY update, a security fix is told apart by phase 5, and a person applies them" "${lag:-UNMEASURED — probe: \`scripts/drills/updates.sh\`}" "a patch within 7 days, an exploited CVE at the next window"

# 7. Simple --------------------------------------------------------------------------
# No Minimal profile exists before the installer of phase 6: until then the figure is
# what the path from a bare machine really asked, each answer a call in the drill.
answers=$(measured deploy-answers)
row "7 simple" "answers the path from a bare machine demands, to an app with a database and sign-in" "${answers:-UNMEASURED — probe: \`scripts/drills/deploy.sh\`}" "capped; a module for hosters never raises it"

# How the sessions work ---------------------------------------------------------------
largest=$(wc -m .claude/rules/*.md | grep -v ' total$' | sort -n | tail -1)
row "sessions" "largest path-scoped rule, in characters (Claude Code cuts at 40,000 on a 200K window)" "${largest// .claude\/rules\// }" "well under 40,000"
row "sessions" "\`CLAUDE.md\` lines (every session reads all of them)" "$(wc -l <CLAUDE.md)" "≤ 200"
