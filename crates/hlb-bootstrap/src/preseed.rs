//! Debian preseed for an automated netinst — designed, then deferred, then written
//! with one hard rule.
//!
//! ## Why this exists at all
//!
//! For one machine, the manual netinst is twenty minutes and a preseed you have to
//! debug is longer. This only pays off once several machines are built the same way —
//! which is also exactly when a mistake in the template stops being a one-off typo and
//! starts being a pattern.
//!
//! ## 🔴 The system disk must be pinned by `/dev/disk/by-id/`
//!
//! `/dev/sdX` is assigned at boot order, not by identity: a preseed built on it can come
//! back pointing at a different disk the next time the machine boots. Left to guess, the
//! installer's automatic partitioning picks "the largest disk" — on a machine that
//! already carries a ZFS pool on other disks, that is precisely the one that must not be
//! touched, and partitioning gives no confirmation and no way back. So generation FAILS
//! outright when the disk is not named this way: printing a preseed that might wipe the
//! wrong disk is worse than refusing to print one.
//!
//! ## Never written to disk by this crate
//!
//! Like `zfs::export_line`, this only renders text. Feeding it to an installer — on a
//! USB stick, or served over HTTP to a PXE boot — is left to the operator, the same way
//! `/etc/exports` is printed rather than appended to.

use thiserror::Error;

#[derive(Debug, Error, PartialEq, Eq)]
pub enum PreseedError {
    #[error(
        "the system disk must be named by /dev/disk/by-id/... (\"{0}\" is not): \
         /dev/sdX is assigned at boot and can point at a different disk next time"
    )]
    DiskNotPinned(String),
    #[error("hostname cannot be empty")]
    EmptyHostname,
    #[error("the SSH key looks empty: it would be the only way to reach the machine")]
    EmptyKey,
    /// Each lands in a shell command of the installer: a quote cuts it short, and the
    /// machine finishes installing with no key and no way in.
    #[error("\"{0}\" cannot go into the installer's commands: letters, digits, '.' and '-' only")]
    BadName(String),
    #[error(
        "the SSH key carries a quote, a backslash, '$' or '`' — likely in its comment: it \
         would cut the installer's command short and leave the machine with no key"
    )]
    KeyNotPlain,
}

/// What a preseed needs to be generated safely.
#[derive(Debug, Clone)]
pub struct PreseedConfig {
    pub hostname: String,
    pub domain: String,
    /// 🔴 MUST be a `/dev/disk/by-id/...` path. See the module doc.
    pub disk_by_id: String,
    /// Installed for the created account; its password is locked, so this key is the
    /// only way in.
    pub ssh_authorized_key: String,
    /// Debian mirror hostname. `None` uses the official one.
    pub mirror: Option<String>,
}

/// Renders the preseed file, or refuses when the disk is not safely named.
pub fn generate(cfg: &PreseedConfig) -> Result<String, PreseedError> {
    if cfg.hostname.trim().is_empty() {
        return Err(PreseedError::EmptyHostname);
    }
    if cfg.ssh_authorized_key.trim().is_empty() {
        return Err(PreseedError::EmptyKey);
    }
    if !cfg.disk_by_id.starts_with("/dev/disk/by-id/") {
        return Err(PreseedError::DiskNotPinned(cfg.disk_by_id.clone()));
    }
    for name in [&cfg.hostname, &cfg.domain, &cfg.disk_by_id] {
        let plain = |c: char| c.is_ascii_alphanumeric() || matches!(c, '.' | '-' | '_' | '/' | ':');
        if !name.chars().all(plain) || (name != &cfg.disk_by_id && name.contains(['/', ':', '_'])) {
            return Err(PreseedError::BadName(name.clone()));
        }
    }
    if cfg.ssh_authorized_key.contains(['\'', '"', '\\', '$', '`']) {
        return Err(PreseedError::KeyNotPlain);
    }

    let mirror = cfg.mirror.as_deref().unwrap_or("deb.debian.org");
    let disk = &cfg.disk_by_id;

    Ok(format!(
        "\
# Generated by `hlb node preseed`. Review it, then feed it to the installer yourself:
# on a USB stick, or served over HTTP to a PXE boot. Nothing here is written for you.

d-i debian-installer/locale string en_US
# xkb-keymap, not xkbmap: the installer asks any question it does not recognise, and an
# unattended install then waits at the keyboard screen forever.
d-i keyboard-configuration/xkb-keymap select us

d-i netcfg/get_hostname string {hostname}
d-i netcfg/get_domain string {domain}

d-i mirror/country string manual
d-i mirror/http/hostname string {mirror}
d-i mirror/http/directory string /debian

d-i clock-setup/utc boolean true
d-i time/zone string UTC
d-i clock-setup/ntp boolean true

# The disk is named, never guessed: automatic partitioning otherwise targets \"the
# largest disk\", which on a storage node is the one already carrying data.
d-i partman-auto/disk string {disk}
# partman knows disks only as /dev/vda, /dev/sda...: given the by-id link it matches none
# and stops on \"no root file system\". The link is resolved HERE, on the machine being
# installed, and a link that leads to no disk stops the install.
d-i partman/early_command string \\
    d=\"$(readlink -f {disk})\" && test -b \"$d\" && \\
    debconf-set partman-auto/disk \"$d\" && debconf-set grub-installer/bootdev \"$d\"
d-i partman-auto/method string regular
d-i partman-auto/choose_recipe select atomic
d-i partman-partitioning/confirm_write_new_label boolean true
d-i partman/choose_partition select finish
d-i partman/confirm boolean true
d-i partman/confirm_nooverwrite boolean true

# No password anywhere: the SSH key installed below in late_command is the only way in,
# for root too: `hlb node add` connects as root, and `homelab` cannot sudo without a
# password it does not have. Debian's sshd takes root by key alone (prohibit-password).
d-i passwd/root-login boolean false
d-i passwd/make-user boolean true
d-i passwd/user-fullname string Homelabus
d-i passwd/username string homelab
d-i passwd/user-default-groups string sudo
d-i passwd/user-password-crypted password !

tasksel tasksel/first multiselect standard, ssh-server

d-i grub-installer/bootdev string {disk}
d-i finish-install/reboot_in_progress note

# The hostname is written here because a preseed fetched over the network arrives after
# the network was configured: get_hostname above came too late, and the machine was
# called \"debian\", the Swarm node name, alike on every machine installed this way.
# sshd silently ignores authorized_keys if it or .ssh is group- or world-readable: the
# key looks installed and nothing works. chmod below is not decoration.
d-i preseed/late_command string \\
    in-target sh -c 'echo {hostname} > /etc/hostname'; \\
    in-target sed -i '/^127.0.1.1/d' /etc/hosts; \\
    in-target sh -c 'echo \"127.0.1.1 {hostname}.{domain} {hostname}\" >> /etc/hosts'; \\
    in-target mkdir -p /home/homelab/.ssh /root/.ssh; \\
    in-target sh -c 'echo \"{ssh_key}\" > /home/homelab/.ssh/authorized_keys'; \\
    in-target sh -c 'echo \"{ssh_key}\" > /root/.ssh/authorized_keys'; \\
    in-target chown -R homelab:homelab /home/homelab/.ssh; \\
    in-target chmod 700 /home/homelab/.ssh /root/.ssh; \\
    in-target chmod 600 /home/homelab/.ssh/authorized_keys /root/.ssh/authorized_keys;
",
        hostname = cfg.hostname,
        domain = cfg.domain,
        mirror = mirror,
        disk = disk,
        ssh_key = cfg.ssh_authorized_key.trim(),
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn cfg() -> PreseedConfig {
        PreseedConfig {
            hostname: "nas-01".into(),
            domain: "example.org".into(),
            disk_by_id: "/dev/disk/by-id/ata-Samsung_SSD_1TB_S1234".into(),
            ssh_authorized_key: "ssh-ed25519 AAAAC3... op@laptop".into(),
            mirror: None,
        }
    }

    #[test]
    fn a_disk_named_dev_sda_is_refused() {
        // 🔴 The one rule that justifies the whole module: /dev/sdX is assigned at
        // boot, not by identity.
        let mut c = cfg();
        c.disk_by_id = "/dev/sda".into();
        assert_eq!(
            generate(&c),
            Err(PreseedError::DiskNotPinned("/dev/sda".into()))
        );
    }

    #[test]
    fn an_empty_hostname_is_refused_rather_than_producing_a_broken_file() {
        let mut c = cfg();
        c.hostname = String::new();
        assert_eq!(generate(&c), Err(PreseedError::EmptyHostname));
    }

    #[test]
    fn an_empty_key_is_refused_it_would_be_the_only_way_in() {
        let mut c = cfg();
        c.ssh_authorized_key = "   ".into();
        assert_eq!(generate(&c), Err(PreseedError::EmptyKey));
    }

    #[test]
    fn a_pinned_disk_produces_a_file_naming_it_for_partitioning_and_grub() {
        let out = generate(&cfg()).expect("valid config");
        assert!(
            out.contains("d-i partman-auto/disk string /dev/disk/by-id/ata-Samsung_SSD_1TB_S1234")
        );
        assert!(out.contains(
            "d-i grub-installer/bootdev string /dev/disk/by-id/ata-Samsung_SSD_1TB_S1234"
        ));
    }

    #[test]
    fn the_disk_link_is_resolved_on_the_machine_before_partitioning() {
        // Found by a real netinst: partman matches /dev/vda, never the by-id link, and
        // stopped on "no root file system".
        let out = generate(&cfg()).expect("valid config");
        assert!(out.contains(
            "d=\"$(readlink -f /dev/disk/by-id/ata-Samsung_SSD_1TB_S1234)\" && test -b \"$d\""
        ));
        assert!(out.contains("debconf-set partman-auto/disk \"$d\""));
        assert!(out.contains("debconf-set grub-installer/bootdev \"$d\""));
    }

    #[test]
    fn root_gets_the_key_since_hlb_node_add_connects_as_root() {
        // Found on a real install: root had no key, `homelab` could not sudo, and the
        // machine could not join the cluster at all.
        let out = generate(&cfg()).expect("valid config");
        assert!(out.contains("> /root/.ssh/authorized_keys"));
        assert!(
            out.contains("chmod 600 /home/homelab/.ssh/authorized_keys /root/.ssh/authorized_keys")
        );
    }

    #[test]
    fn the_hostname_is_written_on_the_installed_system() {
        // A preseed fetched over the network arrives after netcfg: the machine was
        // called "debian".
        let out = generate(&cfg()).expect("valid config");
        assert!(out.contains("in-target sh -c 'echo nas-01 > /etc/hostname'"));
        assert!(out.contains("127.0.1.1 nas-01.example.org nas-01"));
    }

    #[test]
    fn what_would_cut_the_installers_commands_short_is_refused() {
        let mut c = cfg();
        c.ssh_authorized_key = "ssh-ed25519 AAAA Léna's laptop".into();
        assert_eq!(generate(&c), Err(PreseedError::KeyNotPlain));
        let mut c = cfg();
        c.hostname = "nas 01".into();
        assert_eq!(generate(&c), Err(PreseedError::BadName("nas 01".into())));
        let mut c = cfg();
        c.disk_by_id = "/dev/disk/by-id/x;reboot".into();
        assert!(matches!(generate(&c), Err(PreseedError::BadName(_))));
    }

    #[test]
    fn the_keyboard_is_answered_under_the_key_the_installer_asks() {
        // `xkbmap` is no key: the question stayed asked and the install waited forever.
        let out = generate(&cfg()).expect("valid config");
        assert!(out.contains("d-i keyboard-configuration/xkb-keymap select us"));
    }

    #[test]
    fn root_login_stays_closed_and_the_password_is_locked() {
        let out = generate(&cfg()).expect("valid config");
        assert!(out.contains("d-i passwd/root-login boolean false"));
        assert!(out.contains("d-i passwd/user-password-crypted password !"));
    }

    #[test]
    fn the_key_permissions_are_set_not_left_to_default() {
        // 🔴 Without this, `sshd` ignores the key silently and nothing works.
        let out = generate(&cfg()).expect("valid config");
        assert!(out.contains("chmod 700 /home/homelab/.ssh"));
        assert!(out.contains("chmod 600 /home/homelab/.ssh/authorized_keys"));
    }

    #[test]
    fn a_missing_mirror_falls_back_to_the_official_one() {
        let out = generate(&cfg()).expect("valid config");
        assert!(out.contains("d-i mirror/http/hostname string deb.debian.org"));
    }

    #[test]
    fn the_preseed_is_plain_ascii() {
        // debconf reads this file, and it gets pasted into terminals and read over SSH
        // on a machine whose locale is not set up yet: plain ASCII is what survives
        // all three.
        let out = generate(&cfg()).expect("valid config");
        assert!(out.is_ascii(), "preseed output must stay plain ASCII");
    }
}
