//! The addy.io / Bitwarden compatible API.
//!
//! ## What this enables
//!
//! Bitwarden and Vaultwarden can generate a disposable address at the moment you create
//! an account on a site: a button in the form, and the alias is created and filled in.
//! It is addy.io's and SimpleLogin's flagship feature, and it is what separates "I can
//! create aliases" from "I create one on every sign-up without thinking".
//!
//! To get that without installing idmail - which would replace Stalwart's directory and
//! therefore could not coexist with `hlb-mail` - Homelabus speaks the same protocol.
//!
//! ## 🔴 The contract is imposed by the CLIENT, not by us
//!
//! An unusual design point: the shape of the requests and responses is fixed by
//! Bitwarden. It was read from its source
//! (`libs/tools/generator/core/src/integration/addy-io.ts`), not guessed:
//!
//! ```text
//! POST /api/v1/aliases
//! Authorization: Bearer <token>
//! { "domain": "example.org", "description": "Generated by Bitwarden (site.com)" }
//!
//! → 200/201  { "data": { "email": "site-k7m2p9@example.org" } }
//! ```
//!
//! Two consequences to accept:
//!
//! 1. **The response is wrapped in `data`.** Bitwarden reads `json.data.email` and
//!    nothing else: returning the address at the root would give an alias created
//!    server-side and a silent error client-side.
//! 2. **201 as much as 200.** Bitwarden accepts both; we return 201, the correct code
//!    for a creation.
//!
//! ## 🔴 The hint comes from the description, and has to be extracted
//!
//! Bitwarden sends a whole sentence: `"Generated by Bitwarden (amazon.fr)"`. Taken
//! as-is it would give an alias `generated-by-bitwarden-amazon-fr-k7m2p9` - long,
//! unreadable, and above all **identical for every site**, which destroys the
//! attribution the whole mechanism exists for.
//!
//! [`hint_from_description`] extracts the hostname from it.

/// The request Bitwarden sends.
#[derive(Debug, Clone, serde::Deserialize, utoipa::ToSchema)]
pub struct CreationRequest {
    /// The domain to create the alias on.
    #[serde(default)]
    pub domain: Option<String>,
    /// Free text. Bitwarden puts the site in it, in parentheses.
    #[serde(default)]
    pub description: Option<String>,
}

/// The response Bitwarden expects.
///
/// ⚠️ The `data` envelope is not decorative: the client reads `json.data.email`.
#[derive(Debug, Clone, serde::Serialize, utoipa::ToSchema)]
pub struct AliasCreated {
    pub data: AliasData,
}

#[derive(Debug, Clone, serde::Serialize, utoipa::ToSchema)]
pub struct AliasData {
    /// The full address, the only field Bitwarden reads.
    pub email: String,
    /// Carried through as-is, so the user finds it again in their manager.
    pub description: String,
    /// Used by clients that later list or delete.
    pub id: String,
    pub active: bool,
}

impl AliasCreated {
    pub fn new(email: impl Into<String>, description: impl Into<String>) -> Self {
        let email = email.into();
        Self {
            data: AliasData {
                // The id IS the address: unique by construction, and it avoids
                // exposing an internal identifier in a public API.
                id: email.clone(),
                email,
                description: description.into(),
                active: true,
            },
        }
    }
}

/// Extracts a usable hint from the description the client sends.
///
/// 🔴 Bitwarden sends `"Generated by Bitwarden (amazon.fr)"`. Without extraction the
/// hint would be identical for every site - and attribution, the only real benefit of
/// per-recipient aliases, would disappear.
pub fn hint_from_description(description: &str) -> Option<String> {
    // Bitwarden puts the hostname in parentheses.
    let raw = match (description.rfind('('), description.rfind(')')) {
        (Some(d), Some(f)) if f > d + 1 => &description[d + 1..f],
        // No parentheses: take the LAST word, not the whole sentence.
        //
        // 🔴 Found by the test: "Website: https://www.fnac.com/basket" gave the hint
        // "website-https". A whole sentence never produces a hostname, and the alias
        // became unreadable while losing the attribution.
        _ => description.split_whitespace().next_back().unwrap_or(""),
    };

    // Strip a protocol prefix and any path.
    let host = raw
        .trim()
        .trim_start_matches("https://")
        .trim_start_matches("http://")
        .split('/')
        .next()
        .unwrap_or("");

    // ⚠️ `www.` and the top-level domain are noise: `amazon` is a better folder name
    // than `www-amazon-fr`, and that is the name being re-read six months later.
    let without_www = host.trim_start_matches("www.");
    let core = without_www.split('.').next().unwrap_or(without_www);

    let clean = crate::generation::clean_hint(core);

    // ⚠️ A hint identical for every site distinguishes nothing: a purely random alias
    // beats a "bitwarden-" stuck on everything.
    const USELESS: &[&str] = &["generated", "bitwarden", "by", "website", "http", "https"];
    (!clean.is_empty() && !USELESS.contains(&clean.as_str())).then_some(clean)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_response_is_wrapped_the_way_bitwarden_reads_it() {
        // 🔴 The client reads `json.data.email` and nothing else. Returning the address
        // at the root would give an alias created server-side and a silent error
        // client-side - the worst of both worlds, since the alias would exist with
        // nobody knowing.
        let r = AliasCreated::new("amazon-k7m2p9@example.fr", "Generated by Bitwarden");
        let j = serde_json::to_value(&r).expect("serialisation");

        assert_eq!(
            j["data"]["email"], "amazon-k7m2p9@example.fr",
            "the address must sit under `data`: {j}"
        );
        assert!(j.get("email").is_none(), "not at the root: {j}");
    }

    #[test]
    fn the_hostname_is_extracted_from_bitwardens_sentence() {
        // 🔴 Without extraction the hint would be "generated-by-bitwarden-..." for
        // EVERY site. Attribution - knowing who leaked the address - would no longer
        // exist, and that is the whole point of per-recipient aliases.
        assert_eq!(
            hint_from_description("Generated by Bitwarden (amazon.fr)"),
            Some("amazon".into())
        );
        assert_eq!(
            hint_from_description("Website: https://www.fnac.com/panier"),
            Some("fnac".into())
        );
    }

    #[test]
    fn a_bare_hostname_works_too() {
        // Not every client uses Bitwarden's form.
        assert_eq!(
            hint_from_description("leboncoin.fr"),
            Some("leboncoin".into())
        );
        assert_eq!(hint_from_description("  Fnac  "), Some("fnac".into()));
    }

    #[test]
    fn a_useless_hint_is_dropped_rather_than_kept() {
        // A purely random alias beats a "generated-" stuck on everything: a hint that
        // is the same everywhere distinguishes nothing and clutters the address.
        assert_eq!(hint_from_description("Generated by Bitwarden"), None);
        assert_eq!(hint_from_description(""), None);
        assert_eq!(hint_from_description("   "), None);
        assert_eq!(hint_from_description("()"), None);
    }

    #[test]
    fn the_www_prefix_and_tld_are_noise() {
        // ⚠️ `amazon` is a better folder name than `www-amazon-fr`, and that is the
        // name being re-read six months later while tracking down a spam.
        assert_eq!(
            hint_from_description("(www.amazon.fr)"),
            Some("amazon".into())
        );
        assert_eq!(
            hint_from_description("(shop.example.co.uk)"),
            Some("shop".into())
        );
    }

    #[test]
    fn a_request_without_anything_is_still_valid() {
        // Some clients send neither domain nor description: the alias will be random,
        // on the default domain. Degraded, not broken.
        let r: CreationRequest = serde_json::from_str("{}").expect("empty body accepted");
        assert!(r.domain.is_none());
        assert!(r.description.is_none());
    }

    #[test]
    fn the_real_bitwarden_body_deserialises() {
        // The exact shape read from Bitwarden's source.
        let body = r#"{"domain":"example.fr","description":"Generated by Bitwarden (site.com)"}"#;
        let r: CreationRequest = serde_json::from_str(body).expect("real body");
        assert_eq!(r.domain.as_deref(), Some("example.fr"));
        assert_eq!(
            hint_from_description(&r.description.unwrap()),
            Some("site".into())
        );
    }

    #[test]
    fn the_id_is_the_address_not_an_internal_identifier() {
        // Exposing an internal identifier in a public API buys nothing and couples the
        // client to our schema.
        let r = AliasCreated::new("x@example.fr", "note");
        assert_eq!(r.data.id, r.data.email);
    }
}
