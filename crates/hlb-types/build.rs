//! Carries every release's schema (`schemas/<version>.json`) in the binary.
//!
//! `catalog validate` holds a manifest to the schema of the oldest `hlb` its range
//! accepts, and a catalog is validated far from this repository. The directory is
//! walked, never listed: a release's file is carried without anyone remembering to.

use std::path::{Path, PathBuf};

fn main() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("schemas");
    println!("cargo:rerun-if-changed={}", root.display());

    let mut files: Vec<PathBuf> = match std::fs::read_dir(&root) {
        Ok(entries) => entries
            .flatten()
            .map(|e| e.path())
            .filter(|p| p.extension().is_some_and(|e| e == "json"))
            .collect(),
        Err(e) => panic!("reading {}: {e}", root.display()),
    };
    files.sort();

    let mut out = String::from("/// `(version, schema)`, generated by build.rs.\n");
    out.push_str("pub const RELEASE_SCHEMAS: &[(&str, &str)] = &[\n");
    for path in &files {
        let version = path
            .file_stem()
            .map(|s| s.to_string_lossy().to_string())
            .unwrap_or_default();
        let abs = path.canonicalize().unwrap_or_else(|_| path.clone());
        out.push_str(&format!(
            "    ({version:?}, include_str!({:?})),\n",
            abs.display().to_string()
        ));
        println!("cargo:rerun-if-changed={}", path.display());
    }
    out.push_str("];\n");

    let dest = PathBuf::from(std::env::var("OUT_DIR").unwrap_or_default()).join("schemas.rs");
    if let Err(e) = std::fs::write(&dest, out) {
        panic!("writing {}: {e}", dest.display());
    }
}
