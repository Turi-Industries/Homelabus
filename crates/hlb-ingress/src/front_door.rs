//! The front door: HAProxy on the house's site, relaying TCP home without decrypting it.
//!
//! The certificates and every key stay at home: the VPS sees encrypted bytes and the
//! name a client asked for, nothing more. Each house node on the site link is a backend;
//! the health check finds the one Caddy runs on, so Caddy may move without the door
//! being told.
//!
//! 🔴 **The client's address crosses on the PROXY protocol, or the house sees the VPS.**
//! Without it every visitor reaches Caddy from `10.43.0.1` — a private address, which a
//! private route lets in: the whole internet would be "at home". Caddy reads the header
//! from the link's network alone, and the link's network is never one of the private
//! ranges ([`crate::caddyfile`]): a header lost on the way makes a visitor the VPS, and
//! the VPS is a stranger.

use std::fmt::Write as _;
use std::net::Ipv4Addr;

/// HAProxy, the LTS line, pinned by digest.
pub const IMAGE: &str =
    "haproxy:3.2.26-alpine@sha256:96ec3c75a9264ba94e733eeacb44051ed6e7b79bb77a73c2c36f236b6423f1f0";

/// The service on the site's own Swarm.
pub const SERVICE: &str = "hlb-front-door";

/// On the VPS: the directory mounted read-only where the image reads its configuration.
pub const CONFIG_DIR: &str = "/etc/hlb/front-door";

/// Where the image reads it, inside the container.
pub const MOUNTED_AT: &str = "/usr/local/etc/haproxy";

/// The link's network: what Caddy takes a PROXY header from, and what is never private.
pub const SITE_NETWORK: &str = "10.43.0.0/24";

/// A house node the door may send to: its address on the site link.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Backend {
    pub name: String,
    pub address: Ipv4Addr,
}

/// `haproxy.cfg`. Backends sorted by name, so one house renders one file.
pub fn render(backends: &[Backend]) -> String {
    let mut backends = backends.to_vec();
    backends.sort_by(|a, b| a.name.cmp(&b.name));
    let mut out = String::new();
    out.push_str(
        "# Generated by Homelabus - do not edit by hand.\n\
         # The house's front door: TCP relayed home, never decrypted.\n\
         global\n\
         \tmaxconn 4096\n\
         \tlog stdout format raw local0 notice\n\
         \n\
         defaults\n\
         \tmode tcp\n\
         \tlog global\n\
         \toption dontlognull\n\
         \ttimeout connect 5s\n\
         \ttimeout check 3s\n\
         \t# A websocket or a long download stays open: an hour of silence, not a minute.\n\
         \ttimeout client 1h\n\
         \ttimeout server 1h\n\
         \ttimeout tunnel 1h\n",
    );
    // 80 goes to 80 as it came: Caddy only redirects there, and answers ACME's
    // challenges. 443 goes to the relay port, where the visitor's address is read off
    // the PROXY header and nothing is ever taken for the house.
    let relay = crate::caddyfile::RELAY_HTTPS_PORT;
    for (port, home, name, proxy) in [
        (80, 80, "http", ""),
        (443, relay, "https", " send-proxy-v2"),
    ] {
        let _ = write!(
            out,
            "\nfrontend {name}\n\
             \tbind :{port}\n\
             \tdefault_backend house_{name}\n\
             \nbackend house_{name}\n\
             \t# Caddy answers on one node: the check finds it on port 80.\n\
             \toption httpchk\n\
             \thttp-check send meth HEAD uri / ver HTTP/1.1 hdr Host front-door.check\n\
             \thttp-check expect rstatus ^[1-5]\n"
        );
        for b in &backends {
            let _ = writeln!(
                out,
                "\tserver {} {}:{home} check port 80 inter 5s fall 2 rise 2{proxy}",
                b.name, b.address
            );
        }
    }
    out
}

/// The site's own Caddy, which serves the lifeboat once the site is promoted. Reached
/// on the lifeboat's overlay, by name: it runs nowhere else and publishes no port.
pub const SITE_CADDY: &str = "hlb-site-caddy";

/// `haproxy.cfg` once the site is promoted: `names` — the lifeboat's — go to the site's
/// own Caddy, every other name home as before.
///
/// Still never decrypted here: 443 is told apart by the name the client's hello asks
/// for (SNI), 80 by its `Host` — plain HTTP, where Let's Encrypt asks the site's Caddy
/// for its HTTP-01 challenges.
pub fn render_promoted(backends: &[Backend], names: &[String]) -> String {
    let mut names = names.to_vec();
    names.sort();
    names.dedup();
    let home = render(backends);
    let listed = names.join(" ");
    let mut out = String::new();
    for line in home.lines() {
        match line {
            // Docker's own resolver: the site's Caddy is a name on the overlay, and
            // HAProxy starts while it runs no task (`init-addr none`).
            "defaults" => {
                out.push_str(
                    "resolvers docker
                     	nameserver docker 127.0.0.11:53
                     	hold valid 10s
                     
                     defaults
",
                );
            }
            "frontend http" => {
                let _ = write!(
                    out,
                    "frontend http
                     	mode http
                     	# A client trickling its request holds nothing for an hour.
                     	timeout http-request 10s
                     	acl lifeboat req.hdr(host),field(1,:),lower -m str {listed}
                     	use_backend lifeboat_http if lifeboat
"
                );
            }
            "backend house_http" => {
                out.push_str(
                    "backend house_http
	mode http
",
                );
            }
            "frontend https" => {
                let _ = write!(
                    out,
                    "frontend https
                     	tcp-request inspect-delay 5s
                     	tcp-request content accept if {{ req.ssl_hello_type 1 }}
                     	use_backend lifeboat_https if {{ req.ssl_sni,lower -m str {listed} }}
"
                );
            }
            l => {
                out.push_str(l);
                out.push('\n');
            }
        }
    }
    let relay = crate::caddyfile::RELAY_HTTPS_PORT;
    let _ = write!(
        out,
        "\n# The lifeboat: the site's own Caddy, on the lifeboat's overlay.\n\
         backend lifeboat_http\n\
         \tmode http\n\
         \tserver {SITE_CADDY} {SITE_CADDY}:80 resolvers docker init-addr none\n\
         \nbackend lifeboat_https\n\
         \tserver {SITE_CADDY} {SITE_CADDY}:{relay} resolvers docker init-addr none send-proxy-v2\n"
    );
    out
}

/// IPv4 ranges covering `base` except `hole`, ascending. `[base]` when the hole is not
/// inside it.
pub fn without(base: (Ipv4Addr, u8), hole: (Ipv4Addr, u8)) -> Vec<(Ipv4Addr, u8)> {
    let mask = |len: u8| {
        if len == 0 {
            0
        } else {
            u32::MAX << (32 - u32::from(len))
        }
    };
    let (b, bl) = (u32::from(base.0) & mask(base.1), base.1);
    let (h, hl) = (u32::from(hole.0) & mask(hole.1), hole.1);
    if hl < bl || h & mask(bl) != b {
        return vec![(Ipv4Addr::from(b), bl)];
    }
    // At each length from just under the base down to the hole's, the half NOT holding
    // the hole is kept whole.
    let mut out: Vec<(Ipv4Addr, u8)> = (bl + 1..=hl)
        .map(|len| {
            let sibling = (h & mask(len)) ^ (1 << (32 - u32::from(len)));
            (Ipv4Addr::from(sibling), len)
        })
        .collect();
    out.sort();
    out
}

/// `10.43.0.0/24` as a pair.
pub fn site_network() -> (Ipv4Addr, u8) {
    (Ipv4Addr::new(10, 43, 0, 0), 24)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn house() -> Vec<Backend> {
        vec![
            Backend {
                name: "deb2".into(),
                address: Ipv4Addr::new(10, 43, 0, 3),
            },
            Backend {
                name: "deb1".into(),
                address: Ipv4Addr::new(10, 43, 0, 2),
            },
        ]
    }

    #[test]
    fn the_door_relays_tcp_and_never_holds_a_certificate() {
        let c = render(&house());
        assert!(c.contains("\tmode tcp\n"), "{c}");
        for never in ["mode http", "ssl", "crt "] {
            assert!(!c.contains(never), "{never} in the door: {c}");
        }
    }

    #[test]
    fn https_carries_the_clients_address_to_the_relay_port() {
        // 🔴 Without the header every visitor reaches Caddy as the VPS; on 443 rather
        // than the relay port, Caddy would not read it at all.
        let c = render(&house());
        let https = c.split("\nbackend house_https\n").nth(1).expect("https");
        let servers: Vec<_> = https
            .lines()
            .filter(|l| l.trim_start().starts_with("server "))
            .collect();
        assert_eq!(servers.len(), 2, "{c}");
        for s in servers {
            assert!(s.contains(":10443 check port 80"), "{s}");
            assert!(s.ends_with(" send-proxy-v2"), "{s}");
        }
    }

    #[test]
    fn http_goes_home_as_it_came() {
        let c = render(&house());
        let http = c.split("\nbackend house_http\n").nth(1).expect("http");
        let http = http.split("frontend").next().expect("its end");
        assert!(
            http.contains("server deb1 10.43.0.2:80 check port 80"),
            "{c}"
        );
        assert!(
            !http.contains("send-proxy"),
            "Caddy's 80 reads no header: {c}"
        );
        assert!(
            c.contains("bind :80\n\tdefault_backend house_http\n"),
            "{c}"
        );
        assert!(
            c.contains("bind :443\n\tdefault_backend house_https\n"),
            "{c}"
        );
    }

    #[test]
    fn one_house_renders_one_file() {
        let mut reversed = house();
        reversed.reverse();
        assert_eq!(render(&house()), render(&reversed));
    }

    #[test]
    fn a_hole_is_cut_out_of_its_range_exactly() {
        let ten = (Ipv4Addr::new(10, 0, 0, 0), 8);
        let r = without(ten, site_network());
        assert_eq!(r.len(), 16);
        let inside = |ip: Ipv4Addr| {
            r.iter().any(|(n, l)| {
                let m = u32::MAX << (32 - u32::from(*l));
                u32::from(ip) & m == u32::from(*n)
            })
        };
        assert!(
            !inside(Ipv4Addr::new(10, 43, 0, 1)),
            "the VPS is never private"
        );
        assert!(!inside(Ipv4Addr::new(10, 43, 0, 255)));
        for still in [
            Ipv4Addr::new(10, 0, 0, 1),
            Ipv4Addr::new(10, 42, 0, 2),
            Ipv4Addr::new(10, 43, 1, 0),
            Ipv4Addr::new(10, 42, 255, 255),
            Ipv4Addr::new(10, 255, 255, 255),
        ] {
            assert!(inside(still), "{still} left out");
        }
        // Every address of 10/8 but the hole's 256, counted.
        let total: u64 = r.iter().map(|(_, l)| 1u64 << (32 - u32::from(*l))).sum();
        assert_eq!(total, (1 << 24) - 256);
    }

    #[test]
    fn a_hole_elsewhere_leaves_the_range_whole() {
        let r = without((Ipv4Addr::new(192, 168, 0, 0), 16), site_network());
        assert_eq!(r, vec![(Ipv4Addr::new(192, 168, 0, 0), 16)]);
    }

    fn names() -> Vec<String> {
        vec!["vault.example.fr".into(), "id.example.fr".into()]
    }

    #[test]
    fn a_promoted_door_sends_the_lifeboat_s_names_to_the_site_and_the_rest_home() {
        let c = render_promoted(&house(), &names());
        assert!(
            c.contains(
                "use_backend lifeboat_https if { req.ssl_sni,lower -m str id.example.fr \
                 vault.example.fr }"
            ),
            "{c}"
        );
        assert!(
            c.contains("acl lifeboat req.hdr(host),field(1,:),lower -m str id.example.fr"),
            "{c}"
        );
        assert!(
            c.contains("bind :443\n\tdefault_backend house_https\n"),
            "everything else still goes home: {c}"
        );
        // The visitor's address survives to the site's Caddy as it does home.
        let lifeboat = c
            .split("\nbackend lifeboat_https\n")
            .nth(1)
            .expect("lifeboat");
        assert!(lifeboat.contains(":10443 resolvers docker"), "{c}");
        assert!(lifeboat.trim_end().ends_with("send-proxy-v2"), "{c}");
        let home = c.split("\nbackend house_https\n").nth(1).expect("home");
        assert!(home.contains("10.43.0.2:10443 check port 80"), "{c}");
    }

    #[test]
    fn a_promoted_door_still_decrypts_nothing() {
        let c = render_promoted(&house(), &names());
        for never in ["ssl crt", "crt ", " ssl "] {
            assert!(!c.contains(never), "{never} in the door: {c}");
        }
        // Plain HTTP alone is read, on 80.
        let https = c.split("frontend https").nth(1).expect("https");
        let https = https.split("\nbackend").next().expect("its end");
        assert!(!https.contains("mode http"), "{c}");
    }

    #[test]
    fn the_image_is_pinned_by_digest() {
        assert!(IMAGE.contains("@sha256:"));
    }
}
