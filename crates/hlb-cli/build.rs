//! Carries the catalog's YAML in the binary.
//!
//! The only manual step is meant to be downloading `hlb`: a node holding the binary
//! alone had no catalog, and `hlb storage init` stopped on "catalog not found" until one
//! was copied by hand. The directory is walked, never listed: a manifest added tomorrow
//! is carried without anyone remembering to.

use std::path::{Path, PathBuf};

fn main() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../catalog");
    println!("cargo:rerun-if-changed={}", root.display());

    let mut files = Vec::new();
    walk(&root, &mut files);
    files.sort();
    // A build that could not read the catalog carried an empty one, and `hlb` on a bare
    // node answered "0 manifests valid" as if that were the catalog.
    if !files.iter().any(|p| p.ends_with("manifest.yaml")) {
        panic!("no manifest.yaml under {}", root.display());
    }

    let mut out = String::from("/// `(path under the catalog, content)`, generated by build.rs.\n");
    out.push_str("pub const FILES: &[(&str, &str)] = &[\n");
    for path in &files {
        let rel = path
            .strip_prefix(&root)
            .unwrap_or(path)
            .to_string_lossy()
            .replace('\\', "/");
        let abs = path.canonicalize().unwrap_or_else(|_| path.clone());
        out.push_str(&format!(
            "    ({rel:?}, include_str!({:?})),\n",
            abs.display().to_string()
        ));
        println!("cargo:rerun-if-changed={}", path.display());
    }
    out.push_str("];\n");

    let dest = PathBuf::from(std::env::var("OUT_DIR").unwrap_or_default()).join("catalog.rs");
    if let Err(e) = std::fs::write(&dest, out) {
        panic!("writing {}: {e}", dest.display());
    }
}

fn walk(dir: &Path, files: &mut Vec<PathBuf>) {
    let entries = match std::fs::read_dir(dir) {
        Ok(entries) => entries,
        Err(e) => panic!("reading {}: {e}", dir.display()),
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            walk(&path, files);
            // A directory's rename or removal changes what is carried.
            println!("cargo:rerun-if-changed={}", path.display());
        } else if path.extension().is_some_and(|e| e == "yaml") {
            files.push(path);
        }
    }
}
