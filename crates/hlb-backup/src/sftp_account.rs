//! An account of the site that the house pushes into over SFTP, and nothing else: one
//! per pusher, chrooted to its own directory, its key root's. Litestream's
//! (`sqlite_ship`) and the volumes' (`volume_ship`) are two families of them, each
//! with a drop-in of its own.
//!
//! 🔴 **Pushed, never pulled.** The account has no shell, no forwarding, and sees one
//! directory (`internal-sftp`, `ChrootDirectory`): a key read out of a pusher's
//! container at home rewrites that pusher's copy on the VPS and nothing else.

/// Linux refuses a user name longer than this.
const USER_MAX: usize = 32;

/// A family of accounts: every one named `<prefix><name>`, matched by one drop-in, so
/// it is written once whatever pushers come later.
pub struct Accounts {
    pub prefix: &'static str,
    /// Where each account's chroot is, `<site_root>/<user>`, owned by root as sshd
    /// demands.
    pub site_root: &'static str,
    /// The one directory an account may write, inside its chroot.
    pub writable: &'static str,
    pub drop_in: &'static str,
    /// Each account's public key, `<keys_dir>/<user>.pub`: root's, outside the chroot,
    /// so the account cannot add a key of its own.
    pub keys_dir: &'static str,
    /// What connects through them, for the messages.
    pub tool: &'static str,
}

impl Accounts {
    /// The site account of `name`'s pusher. An error when it would not fit Linux.
    pub fn user(&self, name: &str) -> Result<String, String> {
        let u = format!("{}{name}", self.prefix);
        if u.len() > USER_MAX {
            return Err(format!(
                "{name}'s {} account {u} is longer than {USER_MAX} characters",
                self.tool
            ));
        }
        Ok(u)
    }

    /// Where `user` writes on the site, as root sees it.
    pub fn writable_dir(&self, user: &str) -> String {
        format!("{}/{user}/{}", self.site_root, self.writable)
    }

    /// The drop-in itself. `%u` names the account connecting, so one block serves all.
    pub fn drop_in(&self) -> String {
        let Self {
            prefix,
            site_root,
            writable,
            keys_dir,
            tool,
            ..
        } = self;
        format!(
            r#"# Generated by Homelabus - do not edit by hand.
# The house's {tool} accounts: SFTP into their own directory, nothing else.
Match User {prefix}*
    ChrootDirectory {site_root}/%u
    ForceCommand internal-sftp -d /{writable}
    AuthorizedKeysFile {keys_dir}/%u.pub
    AuthenticationMethods publickey
    PasswordAuthentication no
    AllowTcpForwarding no
    AllowStreamLocalForwarding no
    AllowAgentForwarding no
    X11Forwarding no
    PermitTunnel no
    PermitTTY no
"#
        )
    }

    /// Run as root on the site: the account, its chroot, its key and the drop-in —
    /// checked by `sshd -t` before the reload, a refused one put back as it was. Then
    /// proved: sshd itself is asked what it applies to the account, since a drop-in an
    /// `sshd_config` without `Include` never reads changes nothing and says nothing.
    pub fn setup_script(&self, user: &str, public_key: &str) -> String {
        let key = public_key.trim().replace('\'', "");
        let drop_in = self.drop_in();
        let Self {
            site_root,
            writable,
            drop_in: path,
            keys_dir,
            tool,
            ..
        } = self;
        format!(
            r#"set -eu
user={user}
id -u "$user" >/dev/null 2>&1 ||
    useradd --system --no-create-home --home-dir / --shell /usr/sbin/nologin "$user"
install -d -m 755 -o root -g root {site_root} {site_root}/"$user" {keys_dir}
install -d -m 700 -o "$user" -g "$user" {site_root}/"$user"/{writable}
printf '%s\n' 'restrict {key}' > {keys_dir}/"$user".pub.new
chmod 644 {keys_dir}/"$user".pub.new
mv -f {keys_dir}/"$user".pub.new {keys_dir}/"$user".pub

cat > {path}.new <<'HLB_EOF'
{drop_in}HLB_EOF
if cmp -s {path}.new {path}; then
    rm -f {path}.new
else
    [ ! -f {path} ] || cp -p {path} {path}.old
    mv -f {path}.new {path}
    if ! out=$(/usr/sbin/sshd -t 2>&1); then
        if [ -f {path}.old ]; then mv -f {path}.old {path}; else rm -f {path}; fi
        echo "sshd refused the drop-in, put back: $out" >&2
        exit 1
    fi
    rm -f {path}.old
    systemctl reload ssh 2>/dev/null || systemctl reload sshd
fi

# `sshd -T` prints the drop-in's `%u` as written, never expanded (OpenSSH 9.2).
applied=$(/usr/sbin/sshd -T -C "user=$user,host=house,addr=127.0.0.1")
printf '%s\n' "$applied" | grep -qx "chrootdirectory {site_root}/%u" || {{
    echo "sshd does not apply {path} to $user: does sshd_config Include sshd_config.d/*.conf?" >&2
    exit 1; }}
for kind in allowusers allowgroups; do
    allowed=$(printf '%s\n' "$applied" | sed -n "s/^$kind //p" | tr '\n' ' ')
    [ -n "$allowed" ] || continue
    ok=
    for p in $allowed; do
        # Globbed as sshd matches it. The account's group carries its name (useradd).
        case "$user" in $p) ok=1 ;; esac
    done
    [ -n "$ok" ] || {{
        echo "sshd's $kind ($allowed) refuses $user: add it there for {tool} to reach the site" >&2
        exit 1; }}
done
"#
        )
    }
}

/// The site's host key files, ECDSA first: Go's SSH client asks for it first.
pub const HOST_KEYS: [&str; 3] = [
    "/etc/ssh/ssh_host_ecdsa_key.pub",
    "/etc/ssh/ssh_host_rsa_key.pub",
    "/etc/ssh/ssh_host_ed25519_key.pub",
];

#[cfg(test)]
mod tests {
    use super::*;

    const T: Accounts = Accounts {
        prefix: "hlb-t-",
        site_root: "/var/lib/t",
        writable: "w",
        drop_in: "/etc/ssh/sshd_config.d/t.conf",
        keys_dir: "/etc/ssh/t",
        tool: "Tester",
    };

    #[test]
    fn a_name_too_long_for_linux_is_refused() {
        assert_eq!(T.user("x").expect("fits"), "hlb-t-x");
        assert!(T.user(&"a".repeat(27)).is_err());
    }

    #[test]
    fn the_drop_in_confines_every_account_of_the_family_to_its_directory() {
        let d = T.drop_in();
        for line in [
            "Match User hlb-t-*",
            "ChrootDirectory /var/lib/t/%u",
            "ForceCommand internal-sftp -d /w",
            "AuthorizedKeysFile /etc/ssh/t/%u.pub",
            "AllowTcpForwarding no",
            "PermitTTY no",
        ] {
            assert!(d.contains(line), "{line} missing from\n{d}");
        }
    }

    #[test]
    fn the_drop_in_is_checked_before_the_reload_and_proved_after() {
        let s = T.setup_script("hlb-t-x", "ssh-ed25519 AAAA k");
        let check = s.find("sshd -t").expect("checked");
        let reload = s.find("systemctl reload").expect("reloaded");
        let proof = s.find("sshd -T -C").expect("proved");
        assert!(check < reload && reload < proof, "{s}");
        assert!(s.contains("'restrict ssh-ed25519 AAAA k'"), "{s}");
        assert!(s.contains("install -d -m 700 -o \"$user\" -g \"$user\" /var/lib/t/\"$user\"/w"));
    }
}
