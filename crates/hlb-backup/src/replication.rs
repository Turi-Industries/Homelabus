//! PostgreSQL streaming replication (phase 2).
//!
//! ## What it changes compared to PITR
//!
//! `hlb dr promote` restores a base backup and replays the WAL: an RTO of about twenty
//! minutes. A replicating standby receives the changes **continuously** and promotes
//! itself in seconds.
//!
//! The two do not replace each other: the standby follows the primary, so it follows its
//! mistakes too. A table erased by accident is replicated immediately. It is the snapshot
//! and PITR that protect against human error; the standby protects against hardware
//! failure.
//!
//! ## 🔴 The replication slot trap
//!
//! It is **exactly** the same as the `archive_command` one, and it is paid for the
//! same way.
//!
//! A slot guarantees the primary keeps the WAL segments until the standby has consumed
//! them. That is what makes replication reliable — and what makes it dangerous: if the
//! standby stops and the slot remains, **`pg_wal` grows indefinitely** until it saturates
//! the primary's disk. The standby was meant to protect production; its absence kills it.
//!
//! Hence [`MAX_SLOT_WAL_KEEP`]: past that, PostgreSQL invalidates the slot and lets the
//! WAL recycle. The standby becomes unrecoverable and will have to be rebuilt — which is
//! **much preferable** to a primary whose disk is full.
//!
//! ## 🔴 Why replication is ASYNCHRONOUS
//!
//! In synchronous mode, the primary waits for the standby's confirmation before
//! committing each transaction. If the standby goes down, **the primary blocks**: no
//! write completes any more. On a two-node homelab, that turns the failure of a fallback
//! node into a total outage — the opposite of what we were after.
//!
//! The cost of asynchronous mode is an RPO of a few hundred milliseconds. It is the right
//! trade-off here, and it is stated rather than endured.

use crate::{Error, Result};

/// How much WAL the primary accepts to retain for an inactive slot.
///
/// 🔴 The setting that stops a dead standby from killing the primary. At `-1`
/// (PostgreSQL's default), retention is **unlimited**: that is the behaviour that fills
/// disks.
///
/// 8 GB leaves ample time to restart a standby after an incident, and stays far below
/// what saturates a node's disk.
pub const MAX_SLOT_WAL_KEEP: &str = "8GB";

/// A standby's slot name.
///
/// ⚠️ PostgreSQL only accepts lowercase letters, digits and "_": a hostname with a dash
/// is refused, on an error that talks about syntax without saying which.
pub fn slot_name(standby: &str) -> Result<String> {
    let sanitized: String = standby
        .to_lowercase()
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect();

    if sanitized.is_empty() || sanitized.len() > 55 {
        return Err(Error::Unexpected(format!(
            "\"{standby}\": standby name unusable as a slot (1 to 55 characters)"
        )));
    }
    Ok(format!("hlb_{sanitized}"))
}

/// The settings to apply on the **primary**.
///
/// ⚠️ `wal_level` and `max_wal_senders` require a restart, as for archiving.
/// Reloaded hot, they are accepted without error and have no effect: replication looks
/// configured and no standby can connect.
pub fn primary_settings(max_standbys: u32) -> String {
    format!(
        "# Generated by Homelabus — primary.\n\
         # ⚠️ wal_level and max_wal_senders require a RESTART, not a reload.\n\
         wal_level = replica\n\
         # One sender per standby, plus a margin for pg_basebackup, which consumes\n\
         # one for the duration of the copy.\n\
         max_wal_senders = {}\n\
         max_replication_slots = {}\n\
         \n\
         # 🔴 THE line that stops a dead standby from saturating the primary's disk.\n\
         # The default (-1) retains WAL WITHOUT LIMIT: past this threshold the slot\n\
         # is invalidated and the standby will have to be rebuilt — much preferable\n\
         # to a primary stopped for lack of space.\n\
         max_slot_wal_keep_size = {MAX_SLOT_WAL_KEEP}\n\
         \n\
         # Asynchronous: in synchronous mode the primary BLOCKS if the standby goes\n\
         # down. On two nodes, that turns the fallback's failure into a total outage.\n\
         synchronous_commit = on\n\
         synchronous_standby_names = ''\n",
        max_standbys + 2,
        max_standbys + 2,
    )
}

/// The settings to apply on the **standby**.
///
/// 🔴 `hot_standby = on` is not a detail: without it the standby answers no query and you
/// cannot check that it is replicating — you would discover the problem at promotion
/// time.
///
/// 🔴 **Apply AFTER `pg_basebackup -R`, never before.** Observed against a real
/// primary/standby pair: `-R` writes its OWN `primary_conninfo` into
/// `postgresql.auto.conf`, with no `application_name`. And `auto.conf` is read **last**
/// and overrides `postgresql.conf`. Applied before, these settings are therefore
/// silently lost — see [`APPLY_AFTER_BASEBACKUP`].
pub fn standby_settings(primary_host: &str, port: u16, slot: &str, user: &str) -> String {
    format!(
        "# Generated by Homelabus — standby.\n\
         # ⚠️ Write into postgresql.auto.conf AFTER `pg_basebackup -R` (which rewrites\n\
         # that file), or apply through ALTER SYSTEM. Before, it is lost.\n\
         # ⚠️ The `standby.signal` file (EMPTY) must exist in the data directory.\n\
         # Without it, PostgreSQL starts as an independent primary and replicates\n\
         # NOTHING — without the slightest warning.\n\
         # 🔴 The password, the one given to CREATE ROLE: this line replaces the one\n\
         # pg_basebackup wrote, and without it the standby is refused (\"no password\n\
         # supplied\"), stays in recovery, answers reads — and replicates nothing.\n\
         primary_conninfo = 'host={primary_host} port={port} user={user} \
         password=… application_name={slot}'\n\
         primary_slot_name = '{slot}'\n\
         \n\
         # Answers read queries: that is what allows CHECKING that replication is\n\
         # advancing, instead of discovering it at promotion time.\n\
         hot_standby = on\n\
         \n\
         # Reports its position to the primary, which feeds pg_stat_replication and\n\
         # makes the lag measurable.\n\
         hot_standby_feedback = on\n"
    )
}

/// The name a standby announces itself under when nobody told it otherwise.
///
/// It is the `walreceiver` default, the one `pg_basebackup -R` produces on its own.
pub const DEFAULT_NAME: &str = "walreceiver";

/// The order-of-operations warning, for the CLI to display.
pub const APPLY_AFTER_BASEBACKUP: &str =
    "⚠️ Apply these settings AFTER `pg_basebackup -R`: the command rewrites\n\
     postgresql.auto.conf, which is read AFTER postgresql.conf and therefore wins.\n\
     Applied before, the application_name is lost and every standby announces itself\n\
     as \"walreceiver\" — and you can then no longer tell WHICH one is falling behind.";

/// The standbys that cannot be told apart.
///
/// 🔴 Two standbys under the same name make `hlb replication status` useless at the worst
/// moment: you see a node falling behind without being able to say which. A single
/// anonymous standby stays identifiable, so it does not deserve an alert.
pub fn indistinguishable(standbys: &[StandbyStatus]) -> Vec<String> {
    let mut names: Vec<&str> = standbys
        .iter()
        .map(|s| s.application_name.as_str())
        .collect();
    names.sort_unstable();

    let mut ambiguous: Vec<String> = Vec::new();
    for name in &names {
        if names.iter().filter(|n| *n == name).count() > 1 && !ambiguous.iter().any(|a| a == name) {
            ambiguous.push((*name).to_string());
        }
    }
    ambiguous
}

/// A standby's state, as the primary sees it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct StandbyStatus {
    pub application_name: String,
    /// `streaming`, `catchup`, `startup`…
    pub state: String,
    /// Lag, in bytes of WAL.
    pub lag_bytes: Option<i64>,
}

/// The level of attention a standby deserves.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Health {
    /// It is keeping up.
    Streaming,
    /// It is catching up — normal after a restart.
    CatchingUp,
    /// 🔴 It has fallen behind: the lag is growing, or the state is not `streaming`.
    Lagging,
    /// 🔴 Absent from `pg_stat_replication`: it is no longer connected at all.
    Disconnected,
}

/// Past this lag, the standby is no longer really keeping up.
///
/// 64 MB = four WAL segments. Below that it is the normal behaviour of a database that
/// writes; above, something is slowing down — network, the standby's disk, or a standby
/// stopped recently.
pub const MAX_LAG_BYTES: i64 = 64 * 1024 * 1024;

/// What the primary is asked about its standbys, one `application_name|state|lag` line
/// each.
///
/// 🔴 A standby that has replayed nothing yet has a NULL `replay_lsn`, and its lag is
/// unknown: `COALESCE(…, 0)` read it as caught up, and a promotion as losing nothing.
/// The empty field parses as `None`.
pub const STANDBYS_QUERY: &str = "SELECT application_name || '|' || state || '|' || \
     COALESCE(pg_wal_lsn_diff(pg_current_wal_lsn(), replay_lsn)::text, '') \
     FROM pg_stat_replication";

/// A WAL size, read by a person.
fn size(bytes: i64) -> String {
    match bytes {
        l if l < 1024 => format!("{l} B"),
        l if l < 1024 * 1024 => format!("{} KB", l / 1024),
        l => format!("{} MB", l / (1024 * 1024)),
    }
}

impl StandbyStatus {
    pub fn health(&self) -> Health {
        match self.state.as_str() {
            "streaming" if self.lag_bytes.is_some_and(|l| l > MAX_LAG_BYTES) => Health::Lagging,
            // Nothing replayed yet: not keeping up until it says how far behind it is.
            "streaming" if self.lag_bytes.is_none() => Health::CatchingUp,
            "streaming" => Health::Streaming,
            "catchup" | "startup" => Health::CatchingUp,
            _ => Health::Lagging,
        }
    }

    pub fn describe(&self) -> String {
        let lag = self.lag_bytes.map_or_else(|| "?".into(), size);

        match self.health() {
            Health::Streaming => {
                format!("✓ {} is keeping up ({lag} behind)", self.application_name)
            }
            Health::CatchingUp => {
                format!("🟠 {} is catching up ({lag})", self.application_name)
            }
            Health::Lagging => format!(
                "🔴 {} has fallen behind — state \"{}\", {lag} behind",
                self.application_name, self.state
            ),
            Health::Disconnected => {
                format!("🔴 {} is no longer connected", self.application_name)
            }
        }
    }
}

/// An inactive slot, retaining WAL for nothing.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct OrphanSlot {
    pub name: String,
    /// WAL retained because of this slot.
    pub retained_bytes: i64,
    /// Has PostgreSQL already invalidated this slot?
    pub invalidated: bool,
}

impl OrphanSlot {
    /// Does this slot put the primary at risk?
    ///
    /// 🔴 An invalidated slot retains nothing any more: it is *useless*, not *dangerous*.
    /// Confusing the two would cry wolf over a slot PostgreSQL has already neutralised,
    /// and would dilute the alert that matters.
    pub fn is_dangerous(&self) -> bool {
        !self.invalidated && self.retained_bytes > MAX_LAG_BYTES
    }

    pub fn describe(&self) -> String {
        if self.invalidated {
            return format!(
                "🟠 slot \"{}\" INVALIDATED: it no longer retains WAL, but the matching \
                 standby is unrecoverable and must be rebuilt.",
                self.name
            );
        }
        if self.is_dangerous() {
            return format!(
                "🔴 slot \"{}\" retains {} MB of WAL with no consumer. It is filling the \
                 PRIMARY's disk. Restart the standby, or drop the slot:\n\
                 \x20   SELECT pg_drop_replication_slot('{}');",
                self.name,
                self.retained_bytes / (1024 * 1024),
                self.name
            );
        }
        // ⚠️ This case is NOT "all is well": `parse_slots` only returns the slots WITH
        // NO consumer. This one still retains little WAL, but it retains — and it will
        // grow as long as the standby does not come back. Saying "active" here would be
        // the opposite of the truth.
        format!(
            "🟠 slot \"{}\" with no consumer, {} KB retained so far. \
             It will grow up to {MAX_SLOT_WAL_KEEP} then be invalidated.",
            self.name,
            self.retained_bytes / 1024
        )
    }
}

/// Whether a standby can be promoted, and what it would cost.
///
/// ## 🔴 Switchover and failover are not the same operation
///
/// A **switchover** is planned: the primary is alive, you stop the writes, the standby
/// catches up, and nothing is lost. A **failover** is what you do when the primary is
/// gone — and it is lossless only if the standby had received everything, which nobody
/// can check once the primary is unreachable.
///
/// Confusing them is how you promote a standby that was 40 MB behind and discover, three
/// days later, the transactions that never arrived.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Promotion {
    /// The primary answers and the standby is caught up: nothing will be lost.
    Switchover,
    /// 🔴 The primary answers, but the standby is behind. Promoting now DROPS the WAL
    /// it has not replayed.
    SwitchoverWouldLose { bytes: i64 },
    /// 🔴 The primary answers, and the standby has replayed nothing it can measure:
    /// what promoting would drop is unknown.
    LagUnknown,
    /// 🔴 The primary does not answer. Whether anything is lost is UNKNOWABLE from here:
    /// the last figure seen may be minutes old, and the primary may have written since.
    Failover { last_known_lag: Option<i64> },
    /// Nothing to promote: this standby is not in `pg_stat_replication`.
    Unknown,
}

impl Promotion {
    /// Decides from what the primary says — `None` when it does not answer.
    pub fn decide(standbys: Option<&[StandbyStatus]>, target: &str) -> Self {
        let Some(list) = standbys else {
            return Self::Failover {
                last_known_lag: None,
            };
        };
        let Some(s) = list.iter().find(|s| s.application_name == target) else {
            // 🔴 Absent from the list while the primary ANSWERS means this standby is
            // not replicating at all. Promoting it would publish a copy frozen at
            // whenever it last connected — which may be weeks.
            return Self::Unknown;
        };
        // 🔴 Lossless is caught up, not "streaming": a standby streaming 60 MB behind
        // was a switchover that "loses nothing", and those 60 MB were the writes the
        // primary had not yet shipped.
        match (s.health(), s.lag_bytes) {
            (Health::Streaming, Some(0)) => Self::Switchover,
            (_, Some(bytes)) => Self::SwitchoverWouldLose { bytes },
            (_, None) => Self::LagUnknown,
        }
    }

    /// Can this be done without `--force`?
    ///
    /// 🔴 Only the lossless case. Everything else is a decision someone must take
    /// knowingly, because it is paid for in transactions.
    pub fn is_safe(&self) -> bool {
        matches!(self, Self::Switchover)
    }

    /// What it means, spelled out.
    ///
    /// ⚠️ No glyph: this text is shown by the CLI and by the interface, and severity
    /// travels through `is_safe` and the caller's colour, which each can restyle.
    pub fn describe(&self) -> String {
        match self {
            Self::Switchover => "the standby is keeping up: promoting it loses nothing".to_string(),
            Self::SwitchoverWouldLose { bytes } => format!(
                "the standby is {} behind. Promoting it now DROPS what it has not \
                 replayed - stop the writes and let it catch up first",
                size(*bytes)
            ),
            Self::LagUnknown => "the standby has replayed nothing the primary can measure: \
                                 what promoting it would drop is unknown"
                .to_string(),
            Self::Failover { last_known_lag } => match last_known_lag {
                Some(l) => format!(
                    "the primary does not answer. The last known lag was {} MB, and it may \
                     have written since: what is lost cannot be known from here",
                    l / (1024 * 1024)
                ),
                None => "the primary does not answer: what is lost cannot be known from here"
                    .to_string(),
            },
            Self::Unknown => "this standby is not replicating: it is absent from \
                              pg_stat_replication, and its copy is frozen at whenever it \
                              last connected"
                .to_string(),
        }
    }
}

/// 🔴 What must be done to the OLD primary before the new one takes writes.
///
/// Two writable databases is the worst outcome of a failover: both accept transactions,
/// they diverge, and merging them afterwards is manual work on data nobody can arbitrate.
/// The old primary is fenced BEFORE the promotion, never after.
pub const FENCE_OLD_PRIMARY: &str =
    "Stop the old primary BEFORE promoting, and keep it stopped. If it comes back \
     believing it is still primary, both databases accept writes and diverge - and \
     nothing merges them afterwards.";

/// Parses `pg_stat_replication`'s output.
///
/// Expected format: `application_name|state|lag_bytes` per line.
pub fn parse_standbys(output: &str) -> Vec<StandbyStatus> {
    output
        .lines()
        .filter_map(|l| {
            let mut c = l.trim().split('|');
            let name = c.next()?.trim();
            if name.is_empty() {
                return None;
            }
            Some(StandbyStatus {
                application_name: name.to_string(),
                state: c.next().unwrap_or("").trim().to_string(),
                lag_bytes: c.next().and_then(|v| v.trim().parse().ok()),
            })
        })
        .collect()
}

/// Parses `pg_replication_slots`'s output.
///
/// Expected format: `slot_name|active|retained_bytes|invalidated`.
pub fn parse_slots(output: &str) -> Vec<OrphanSlot> {
    output
        .lines()
        .filter_map(|l| {
            let mut c = l.trim().split('|');
            let name = c.next()?.trim();
            if name.is_empty() {
                return None;
            }
            let active = c.next().unwrap_or("").trim() == "t";
            let kept: i64 = c.next().and_then(|v| v.trim().parse().ok()).unwrap_or(0);
            let invalid = c.next().unwrap_or("").trim() == "t";

            // An active slot is never an orphan: someone is consuming it.
            (!active).then(|| OrphanSlot {
                name: name.to_string(),
                retained_bytes: kept,
                invalidated: invalid,
            })
        })
        .collect()
}

