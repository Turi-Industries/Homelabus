    #[test]
    fn standby_settings_warn_about_basebackup_order() {
        // 🔴 Observed against a real primary/standby pair: `pg_basebackup -R` writes its
        // own primary_conninfo into postgresql.auto.conf, WITHOUT application_name. Since
        // that file is read last, settings applied before are silently lost. The order
        // must be stated.
        let s = standby_settings("primary.local", 5432, "hlb_nas", "repl");
        assert!(s.contains("application_name=hlb_nas"));
        assert!(
            s.contains("AFTER") && s.contains("pg_basebackup"),
            "the order of operations must be explicit: {s}"
        );
        assert!(APPLY_AFTER_BASEBACKUP.contains(DEFAULT_NAME));
    }

    #[test]
    fn two_standbys_under_the_same_name_are_flagged() {
        // 🔴 The exact symptom of the previous trap: without application_name, every
        // standby announces itself as "walreceiver". You then see a node falling behind
        // without being able to say which — a status that lies by ambiguity.
        let anonymous = |lag| StandbyStatus {
            application_name: DEFAULT_NAME.to_string(),
            state: "streaming".into(),
            lag_bytes: Some(lag),
        };

        assert_eq!(
            indistinguishable(&[anonymous(0), anonymous(0)]),
            [DEFAULT_NAME]
        );

        // A single anonymous standby stays identifiable: no needless alert.
        assert!(indistinguishable(&[anonymous(0)]).is_empty());

        // Distinct names do not either.
        let named = |n: &str| StandbyStatus {
            application_name: n.to_string(),
            state: "streaming".into(),
            lag_bytes: Some(0),
        };
        assert!(indistinguishable(&[named("hlb_a"), named("hlb_b")]).is_empty());

        // And a duplicated name is reported once, not twice.
        assert_eq!(
            indistinguishable(&[named("hlb_a"), named("hlb_a"), named("hlb_b")]),
            ["hlb_a"]
        );
    }

    #[test]
    fn a_young_orphan_slot_is_never_called_active() {
        // 🔴 Observed against a real PostgreSQL: the first version displayed "✓ slot
        // active" for a slot WITH NO consumer that still retained little WAL. That was
        // the opposite of the truth, on the module's costliest failure mode.
        let v = parse_slots("hlb_small01|f|1000|f\n");
        assert_eq!(v.len(), 1);
        assert!(!v[0].is_dangerous(), "not dangerous yet");

        let d = v[0].describe();
        assert!(
            !d.contains("active"),
            "a slot with no consumer is not active: {d}"
        );
        assert!(d.contains("no consumer"), "{d}");
        assert!(d.contains("will grow"), "it must say what will happen: {d}");
    }

    #[test]
    fn a_standby_behind_is_never_a_switchover_that_loses_nothing() {
        // 🔴 Found by review: streaming up to 64 MB behind decided "Switchover", safe
        // without --force, described as losing nothing.
        let behind = [standby("hlb_nas", "streaming", Some(4096))];
        let d = Promotion::decide(Some(&behind), "hlb_nas");
        assert_eq!(d, Promotion::SwitchoverWouldLose { bytes: 4096 });
        assert!(!d.is_safe());
        assert!(d.describe().contains("4 KB"), "{}", d.describe());

        let caught_up = [standby("hlb_nas", "streaming", Some(0))];
        assert!(Promotion::decide(Some(&caught_up), "hlb_nas").is_safe());
    }

    #[test]
    fn a_standby_that_replayed_nothing_has_an_unknown_lag_never_zero() {
        // A NULL `replay_lsn` was coalesced to 0: caught up, by construction.
        assert!(!STANDBYS_QUERY.contains(", 0)"), "{STANDBYS_QUERY}");
        let parsed = parse_standbys("hlb_nas|streaming|\n");
        assert_eq!(parsed[0].lag_bytes, None);
        assert_eq!(parsed[0].health(), Health::CatchingUp);
        let d = Promotion::decide(Some(&parsed), "hlb_nas");
        assert_eq!(d, Promotion::LagUnknown);
        assert!(!d.is_safe());
    }

