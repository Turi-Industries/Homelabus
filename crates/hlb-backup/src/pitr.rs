//! Point-in-time restore for PostgreSQL (layer L2).
//!
//! ## What it brings over the logical dump
//!
//! `pg_dump` (layer L1) gives a consistent snapshot **at the time it runs**. Between two
//! dumps four hours apart, an accidental deletion at 14:05 costs four hours of work: you
//! can only restore to 12:00 or to 16:00 — and 16:00 already contains the deletion.
//!
//! PITR changes that: a **base backup** plus the continuous run of WAL journals lets you
//! replay up to 14:04 exactly.
//!
//! ## 🔴 The danger specific to WAL archiving
//!
//! **A failing `archive_command` does not lose the journals: it keeps them.**
//!
//! PostgreSQL considers an unarchived WAL segment non-recyclable. If the archive
//! destination is full, mounted read-only or simply absent, `pg_wal` grows indefinitely
//! until it saturates the disk — and the server stops dead, for writes as well as reads.
//!
//! In other words: **archiving to a broken destination is more dangerous than not
//! archiving at all.**
//!
//! That is why the agent watches `/archive/wal` and `/archive/base` by default:
//! the archive disk filling up trips the same thresholds as any other filesystem. An
//! absent path is ignored without noise — not every node archives.
//!
//! ## What this module does
//!
//! It **computes and renders configurations**. It executes nothing: restoring a database
//! is a manual operation, decided by a human, and an API that triggered it on its own
//! would be a weapon pointed at the data.

use crate::{Error, Result};

/// A base backup (`pg_basebackup`), the starting point of a replay.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct BaseBackup {
    pub id: String,
    /// The instant the backup **finished**, in seconds since the epoch.
    ///
    /// The end, not the start: the replay can only begin from the moment the file copy is
    /// complete and consistent.
    pub finished_at: i64,
}

/// The window that is really restorable.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Window {
    pub earliest: i64,
    pub latest: i64,
}

impl Window {
    pub fn contains(&self, t: i64) -> bool {
        t >= self.earliest && t <= self.latest
    }

    pub fn describe(&self) -> String {
        format!(
            "from {} to {}",
            iso8601(self.earliest),
            iso8601(self.latest)
        )
    }
}

/// Where the archived WAL segments land.
#[derive(Debug, Clone)]
pub struct WalArchive {
    /// Archive directory, mounted into the PostgreSQL container.
    pub dir: String,
}

impl WalArchive {
    pub fn new(dir: impl Into<String>) -> Self {
        Self { dir: dir.into() }
    }

    /// The archive command for one segment.
    ///
    /// 🔴 The `test ! -f` is not a superfluous precaution: without it, a segment
    /// re-archived after a restart **overwrites** the one already present. If the
    /// contents differ — which happens after a timeline switch — the archive silently
    /// becomes inconsistent and the replay fails on the day you need it. PostgreSQL's
    /// documentation mandates this form.
    ///
    /// 🔴 Copied under a temporary name, then renamed: a `cp` interrupted halfway left
    /// a truncated segment under its real name, every retry then failed `test ! -f`,
    /// and archiving jammed — `pg_wal` growing until the disk was full.
    pub fn archive_command(&self) -> String {
        format!(
            "test ! -f {dir}/%f && cp %p {dir}/%f.tmp && mv {dir}/%f.tmp {dir}/%f",
            dir = self.dir.trim_end_matches('/')
        )
    }

    /// The symmetric command, used during recovery.
    pub fn restore_command(&self) -> String {
        format!("cp {}/%f %p", self.dir.trim_end_matches('/'))
    }

    /// The settings to write into `postgresql.conf`.
    ///
    /// ⚠️ `wal_level` and `archive_mode` require a server **restart**, not a mere
    /// `pg_ctl reload`. A change reloaded hot is accepted without error and has no
    /// effect: archiving looks enabled and archives nothing.
    pub fn render_settings(&self) -> String {
        format!(
            "# Generated by Homelabus — do not edit by hand.\n\
             # ⚠️ These three settings require a RESTART, not a reload.\n\
             wal_level = replica\n\
             archive_mode = on\n\
             archive_command = '{}'\n\
             # Replay margin: an orphan 16 MB segment beats a hole.\n\
             archive_timeout = 300\n\
             wal_keep_size = 1024\n",
            self.archive_command()
        )
    }
}

/// An archived WAL segment.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Segment {
    /// File name, 24 hexadecimal characters.
    pub name: String,
    /// The instant it was archived (the file's modification time).
    pub archived_at: i64,
}

impl Segment {
    /// The segment's timeline — the first 8 digits.
    ///
    /// It changes after every recovery. Two segments from different timelines can cover
    /// the same position without being interchangeable.
    pub fn timeline(&self) -> Option<u32> {
        u32::from_str_radix(self.name.get(..8)?, 16).ok()
    }
}

/// A valid WAL segment name?
///
/// 🔴 The archive directory holds more than segments: PostgreSQL also drops `.history`
/// files (timeline switches), `.backup` files (base-backup markers) and sometimes
/// `.partial`. Counting them as segments would give a WAL coverage wider than it really
/// is — precisely the lie this module exists to avoid.
fn is_segment(name: &str) -> bool {
    name.len() == 24 && name.chars().all(|c| c.is_ascii_hexdigit())
}

/// Inventories the segments really present in the archive directory.
///
/// This is what allows announcing an **observed** upper bound rather than one inferred
/// from the last base backup. Without this inventory the window is underestimated — the
/// safe direction to err in, but still false information.
pub fn scan_archive(dir: &std::path::Path) -> std::io::Result<Vec<Segment>> {
    let mut out = Vec::new();

    for e in std::fs::read_dir(dir)? {
        let e = e?;
        let name = e.file_name().to_string_lossy().to_string();
        if !is_segment(&name) {
            continue;
        }

        let m = e.metadata()?;
        if !m.is_file() {
            continue;
        }

        let at = m
            .modified()
            .ok()
            .and_then(|t| t.duration_since(std::time::UNIX_EPOCH).ok())
            .map(|d| d.as_secs() as i64)
            .unwrap_or(0);

        out.push(Segment {
            name,
            archived_at: at,
        });
    }

    // By name: the lexicographic order of WAL segments IS their chronological order, by
    // construction of the format. Sorting by file date would be less reliable — copying
    // an archive can rewrite the dates without changing the data.
    out.sort_by(|a, b| a.name.cmp(&b.name));
    Ok(out)
}

/// How far the archived journals allow replaying.
///
/// ⚠️ This is the archive time of the last segment, so a **conservative bound**: the
/// current segment, not yet archived, already holds more recent transactions. Announcing
/// further would promise a replay we cannot guarantee.
pub fn wal_coverage(segments: &[Segment]) -> Option<i64> {
    segments.iter().map(|s| s.archived_at).max()
}

/// Why a requested restore is not possible.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Unreachable {
    /// No base backup: WAL alone restores nothing.
    NoBaseBackup,
    /// The target precedes the oldest base backup kept.
    BeforeOldestBase { oldest: i64 },
    /// The target is after the last archived journal.
    AfterLastWal { last: i64 },
}

impl Unreachable {
    pub fn describe(&self) -> String {
        match self {
            Self::NoBaseBackup => "no base backup: WAL alone restores nothing".to_string(),
            Self::BeforeOldestBase { oldest } => {
                format!("earlier than the oldest base backup ({})", iso8601(*oldest))
            }
            Self::AfterLastWal { last } => {
                format!("later than the last archived journal ({})", iso8601(*last))
            }
        }
    }
}

/// The restorable window, based on what is really kept.
///
/// `last_wal_at` is the instant covered by the last archived segment.
pub fn recoverable_window(bases: &[BaseBackup], last_wal_at: i64) -> Option<Window> {
    let oldest = bases.iter().map(|b| b.finished_at).min()?;
    if last_wal_at < oldest {
        // The journals do not even cover the end of the oldest base: nothing is
        // replayable, and pretending otherwise would be worse than saying so.
        return None;
    }
    Some(Window {
        earliest: oldest,
        latest: last_wal_at,
    })
}

/// Chooses the base backup to replay from.
///
/// 🔴 It is the **most recent one at or before** the target. A later base is unusable:
/// WAL replays forward, never backward. An older base would work but would needlessly
/// replay hours of journals.
pub fn base_for(
    bases: &[BaseBackup],
    target: i64,
    last_wal_at: i64,
) -> std::result::Result<&BaseBackup, Unreachable> {
    if bases.is_empty() {
        return Err(Unreachable::NoBaseBackup);
    }
    if target > last_wal_at {
        return Err(Unreachable::AfterLastWal { last: last_wal_at });
    }

    bases
        .iter()
        .filter(|b| b.finished_at <= target)
        .max_by_key(|b| b.finished_at)
        .ok_or_else(|| Unreachable::BeforeOldestBase {
            oldest: bases.iter().map(|b| b.finished_at).min().unwrap_or(target),
        })
}

/// How far the archived journals can be pruned without breaking anything.
///
/// 🔴 The bound is the **oldest** base backup kept, not the most recent. Pruning up to
/// the most recent would make every earlier base unrestorable: they would still exist on
/// disk, would look valid, and would serve no purpose. That is the scenario where you
/// believe you have thirty days of retention and you have one.
pub fn wal_prunable_before(bases: &[BaseBackup]) -> Option<i64> {
    bases.iter().map(|b| b.finished_at).min()
}

/// The recovery configuration to write into `postgresql.auto.conf`.
///
/// ⚠️ Since PostgreSQL 12, `recovery.conf` no longer exists: these parameters go into the
/// normal configuration, and it is the presence of the **`recovery.signal`** file that
/// triggers recovery. A server given these settings without the file created starts
/// normally and ignores the target — without the slightest warning.
pub fn render_recovery(archive: &WalArchive, target: i64) -> String {
    format!(
        "# Generated by Homelabus — point-in-time recovery.\n\
         # ⚠️ ALSO create an empty `recovery.signal` file in the data directory:\n\
         # without it, PostgreSQL starts normally and ignores all of this.\n\
         restore_command = '{restore}'\n\
         recovery_target_time = '{target}'\n\
         # `promote`: the server becomes writable once the target is reached. The\n\
         # default (`pause`) leaves it read-only, which looks a great deal like a\n\
         # failed restore.\n\
         recovery_target_action = 'promote'\n\
         # After a recovery, PostgreSQL creates a new timeline. Without this setting,\n\
         # a SECOND restore to the same point would follow the original timeline and\n\
         # would not find the expected journals.\n\
         recovery_target_timeline = 'latest'\n",
        restore = archive.restore_command(),
        target = pg_timestamp(target),
    )
}

/// Checks a restore is possible, and prepares everything needed.
pub fn plan_recovery(
    bases: &[BaseBackup],
    last_wal_at: i64,
    target: i64,
    archive: &WalArchive,
) -> Result<RecoveryPlan> {
    let base = base_for(bases, target, last_wal_at).map_err(|u| Error::Pitr {
        target: iso8601(target),
        reason: u.describe(),
    })?;

    Ok(RecoveryPlan {
        base: base.clone(),
        target,
        wal_replay_secs: target - base.finished_at,
        config: render_recovery(archive, target),
    })
}

#[derive(Debug, Clone)]
pub struct RecoveryPlan {
    pub base: BaseBackup,
    pub target: i64,
    /// The span of journals to replay. Used to announce an order of magnitude: replaying
    /// six days of WAL does not take the same time as six minutes.
    pub wal_replay_secs: i64,
    pub config: String,
}

impl RecoveryPlan {
    pub fn describe(&self) -> String {
        format!(
            "base {} ({}), replaying {} h {:02} min up to {}",
            self.base.id,
            iso8601(self.base.finished_at),
            self.wal_replay_secs / 3600,
            (self.wal_replay_secs % 3600) / 60,
            iso8601(self.target)
        )
    }
}

/// A readable UTC date, with no calendar dependency.
///
/// The algorithm is Howard Hinnant's (`civil_from_days`): it handles secular leap years
/// correctly, unlike the "a year is 365.25 days" approximations that drift by a day every
/// few centuries.
pub fn iso8601(epoch: i64) -> String {
    let (y, m, d, hh, mm, ss) = civil(epoch);
    format!("{y:04}-{m:02}-{d:02} {hh:02}:{mm:02}:{ss:02} UTC")
}

/// The same date, in the format PostgreSQL expects for `recovery_target_time`.
pub(crate) fn pg_timestamp(epoch: i64) -> String {
    let (y, m, d, hh, mm, ss) = civil(epoch);
    // The `+00` suffix is indispensable: with no timezone, PostgreSQL interprets the
    // date in the server's `TimeZone`, and you restore to an instant shifted by hours
    // with nothing saying so.
    format!("{y:04}-{m:02}-{d:02} {hh:02}:{mm:02}:{ss:02}+00")
}

/// Parses "YYYY-MM-DD HH:MM:SS", **interpreted as UTC**.
///
/// 🔴 No leniency on the timezone: accepting a date without one and interpreting it in
/// the machine's would silently restore to an instant shifted by hours. Here it is UTC,
/// it is said, and the display repeats it.
pub fn parse_utc(s: &str) -> Option<i64> {
    let s = s.trim();
    let (date, hour) = s.split_once(['T', ' '])?;

    let mut d = date.split('-');
    let y: i64 = d.next()?.parse().ok()?;
    let m: i64 = d.next()?.parse().ok()?;
    let day: i64 = d.next()?.parse().ok()?;
    if d.next().is_some() || !(1..=12).contains(&m) || !(1..=31).contains(&day) {
        return None;
    }

    let mut t = hour.trim_end_matches('Z').split(':');
    let hh: i64 = t.next()?.parse().ok()?;
    let mm: i64 = t.next()?.parse().ok()?;
    // Seconds are optional: "14:04" is a perfectly legitimate target.
    let ss: i64 = match t.next() {
        Some(v) => v.parse().ok()?,
        None => 0,
    };
    if t.next().is_some() || hh > 23 || mm > 59 || ss > 59 {
        return None;
    }

    let epoch = days_from_civil(y, m, day) * 86_400 + hh * 3600 + mm * 60 + ss;

    // Round trip: rejects 31 February and friends, which the raw computation would
    // accept by overflowing into the next month.
    let (vy, vm, vd, _, _, _) = civil(epoch);
    if (vy, vm as i64, vd as i64) != (y, m, day) {
        return None;
    }
    Some(epoch)
}

/// The inverse of `civil`, with the same origin shifted to 1 March.
fn days_from_civil(y: i64, m: i64, d: i64) -> i64 {
    let y = if m <= 2 { y - 1 } else { y };
    let era = y.div_euclid(400);
    let yoe = y - era * 400;
    let mp = if m > 2 { m - 3 } else { m + 9 };
    let doy = (153 * mp + 2) / 5 + d - 1;
    let doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    era * 146_097 + doe - 719_468
}

/// Exposed for the other modules that timestamp file names.
pub(crate) fn civil_public(epoch: i64) -> (i64, u32, u32, u32, u32, u32) {
    civil(epoch)
}

fn civil(epoch: i64) -> (i64, u32, u32, u32, u32, u32) {
    let days = epoch.div_euclid(86_400);
    let remaining = epoch.rem_euclid(86_400);

    // Shifts the origin to 1 March 0000: February, with its variable day, ends up at the
    // end of the cycle and drops out of the computation.
    let z = days + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z.rem_euclid(146_097);
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let y = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = (doy - (153 * mp + 2) / 5 + 1) as u32;
    let m = if mp < 10 { mp + 3 } else { mp - 9 } as u32;
    let y = if m <= 2 { y + 1 } else { y };

    (
        y,
        m,
        d,
        (remaining / 3600) as u32,
        ((remaining % 3600) / 60) as u32,
        (remaining % 60) as u32,
    )
}

/// Producing a base backup (`pg_basebackup`).
///
/// 🔴 **Without one, WAL archiving is of no use.** It is the mandatory starting point of
/// every replay: the journals say how to go from one state to another, never what the
/// initial state is. A homelab that had diligently archived its WAL for six months with
/// no base backup at all could restore nothing.
pub mod basebackup {
    use super::*;

    /// Where to write the backup, and what to connect to.
    #[derive(Debug, Clone)]
    pub struct Target {
        /// Volume or host path receiving the copy.
        pub destination: String,
        pub host: String,
        pub port: u16,
        /// 🔴 A role with the `REPLICATION` attribute. The superuser will do, but a
        /// dedicated role limits what a leak of this password would allow.
        pub user: String,
        pub password: String,
        /// Docker network on which the server is reachable.
        pub network: Option<String>,
        /// Client image. Its major version must match the server's.
        pub image: String,
    }

    impl Target {
        pub fn new(destination: impl Into<String>, host: impl Into<String>) -> Self {
            Self {
                destination: destination.into(),
                host: host.into(),
                port: 5432,
                user: "postgres".into(),
                password: String::new(),
                network: None,
                image: crate::images::POSTGRES_CLIENT.into(),
            }
        }

        pub fn credentials(mut self, user: impl Into<String>, password: impl Into<String>) -> Self {
            self.user = user.into();
            self.password = password.into();
            self
        }

        pub fn network(mut self, net: impl Into<String>) -> Self {
            self.network = Some(net.into());
            self
        }

        pub fn image(mut self, image: impl Into<String>) -> Self {
            self.image = image.into();
            self
        }
    }

    /// `pg_basebackup`'s arguments, isolated so they can be tested without Docker.
    ///
    /// Each option carries a consequence:
    ///
    /// - `--format=tar` + `--gzip`: a raw directory tree would be copied file by file,
    ///   and the permissions would be lost on the way onto a mounted volume.
    /// - `--wal-method=stream`: 🔴 **the critical point.** A base backup takes several
    ///   minutes; during that time the server keeps writing. Without the journals
    ///   produced *during* the copy, the backup obtained is inconsistent and PostgreSQL
    ///   refuses to start on it. `stream` opens a second connection that captures them as
    ///   they go. The historical default (`fetch`) additionally requires `wal_keep_size`
    ///   to be large enough, failing which the backup fails *at the end*, after copying
    ///   everything.
    /// - `--checkpoint=fast`: without it, PostgreSQL waits for the next natural
    ///   checkpoint — up to several minutes of waiting before the copy starts.
    /// - `--no-password`: never an interactive prompt. A container waiting for input
    ///   stays blocked until the timeout, without saying anything.
    pub fn args(label: &str) -> Vec<String> {
        [
            "pg_basebackup",
            "--pgdata=/backup",
            "--format=tar",
            "--gzip",
            "--wal-method=stream",
            "--checkpoint=fast",
            "--progress",
            "--no-password",
        ]
        .iter()
        .map(|s| s.to_string())
        .chain(std::iter::once(format!("--label={label}")))
        .collect()
    }

    /// Enriches the errors whose raw message does not say what to do.
    ///
    /// 🔴 `pg_basebackup` goes through the **replication protocol**, not through an
    /// ordinary SQL connection. `pg_hba.conf` treats `replication` as a separate
    /// database: a user who connects perfectly with `psql` is refused for a base backup.
    /// The official image only allows replication from `127.0.0.1`, so never from another
    /// container.
    pub(crate) fn explain(stderr: &str) -> String {
        if stderr.contains("no pg_hba.conf entry for replication") {
            return format!(
                "{stderr}\n\n\
                 🔴 pg_basebackup uses the REPLICATION protocol, which pg_hba.conf\n\
                 treats as a separate database. Connecting with psql therefore proves\n\
                 nothing. The official postgres image only allows it from 127.0.0.1 —\n\
                 never from another container.\n\n\
                 Add this line to pg_hba.conf, then reload:\n\
                 \x20   host replication all all scram-sha-256\n\
                 \x20   psql -U postgres -c 'SELECT pg_reload_conf()'"
            );
        }

        if stderr.contains("must be superuser or replication role")
            || stderr.contains("permission denied to start WAL sender")
        {
            return format!(
                "{stderr}\n\n\
                 🔴 The user does not have the REPLICATION attribute:\n\
                 \x20   ALTER ROLE <user> REPLICATION;"
            );
        }

        if stderr.contains("directory") && stderr.contains("exists and is not empty") {
            return format!(
                "{stderr}\n\n\
                 A backup already carries this name. We NEVER overwrite an existing\n\
                 backup: move it or delete it by hand if it is useless."
            );
        }

        stderr.to_string()
    }

    /// The name of a base backup's subdirectory.
    ///
    /// Timestamped and lexicographically sortable: the order of the names is the
    /// chronological order, which the choice of starting base (`base_for`) depends on.
    pub fn directory_name(at: i64) -> String {
        let (y, m, d, hh, mm, ss) = civil(at);
        format!("base-{y:04}{m:02}{d:02}T{hh:02}{mm:02}{ss:02}Z")
    }

    /// Runs `pg_basebackup` in a container.
    ///
    /// Returns the name of the directory created, which serves as the snapshot id in the
    /// state — it is what `hlb backup pitr plan` will display.
    pub async fn run(target: &Target, at: i64) -> Result<String> {
        let name = directory_name(at);

        let out = command(target, &name)
            .output()
            .await
            .map_err(|e| Error::ResticMissing(format!("docker not found: {e}")))?;

        if !out.status.success() {
            let stderr = String::from_utf8_lossy(&out.stderr).trim().to_string();

            // A failure leaves an empty directory created by the mount. Accumulating one
            // per attempt would clutter the archive with shells indistinguishable from
            // real backups to anyone looking at the disk.
            let _ = tokio::fs::remove_dir(format!(
                "{}/{name}",
                target.destination.trim_end_matches('/')
            ))
            .await;

            return Err(Error::Dump {
                database: format!("base backup \"{name}\""),
                stderr: explain(&stderr),
            });
        }

        tracing::info!(base = %name, "base backup produced");
        Ok(name)
    }

    /// The `docker run` of `pg_basebackup` into the directory `name`.
    pub(crate) fn command(target: &Target, name: &str) -> tokio::process::Command {
        let mut cmd = tokio::process::Command::new("docker");
        cmd.args(["run", "--rm"]);

        if let Some(n) = &target.network {
            cmd.arg("--network");
            cmd.arg(n);
        }

        // As everywhere else: through the environment, never on the command line,
        // readable by every user of the machine.
        let env = [
            ("PGHOST".to_string(), target.host.clone()),
            ("PGPORT".to_string(), target.port.to_string()),
            ("PGUSER".to_string(), target.user.clone()),
            ("PGPASSWORD".to_string(), target.password.clone()),
        ];
        crate::docker_env::pass_by_name(&mut cmd, &env);

        // The subdirectory is created by the mount: `pg_basebackup` requires an EMPTY
        // destination and would fail on an already populated directory — which is exactly
        // the behaviour we want, we never overwrite an existing base.
        cmd.arg("-v");
        cmd.arg(format!(
            "{}/{name}:/backup",
            target.destination.trim_end_matches('/')
        ));

        cmd.arg(&target.image);
        cmd.args(args(name));
        cmd
    }
}

/// The connection credentials extracted from a PostgreSQL URL.
///
/// The CLI already receives `--postgres-admin` in the form
/// `postgres://user:password@host:port/database`. Asking for them separately for the base
/// backup would make two sources of truth diverge — and the day one changes, the backup
/// fails on a refused authentication.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Credentials {
    pub user: String,
    pub password: String,
    pub host: String,
    pub port: u16,
}

/// Parses `postgres://user:password@host:port/database`.
///
/// ⚠️ The password can contain encoded characters (`%40` for `@`). We decode them:
/// passing them through would fail authentication with a perfectly misleading message —
/// "incorrect password" when it is correct.
pub fn parse_pg_url(url: &str) -> Option<Credentials> {
    let remaining = url
        .strip_prefix("postgres://")
        .or_else(|| url.strip_prefix("postgresql://"))?;
    parse_url_after_scheme(remaining, 5432)
}

/// Parses `mysql://user:password@host:port/database`.
///
/// ⚠️ The default port differs (3306). The rest of the parsing is **identical** to
/// PostgreSQL's, notably the split on the LAST `@`: duplicating it would have let the two
/// versions diverge on that detail, which is precisely the one that breaks.
pub fn parse_maria_url(url: &str) -> Option<Credentials> {
    let remaining = url
        .strip_prefix("mysql://")
        .or_else(|| url.strip_prefix("mariadb://"))?;
    parse_url_after_scheme(remaining, 3306)
}

fn parse_url_after_scheme(remaining: &str, default_port: u16) -> Option<Credentials> {
    // Split on the LAST `@`: a password can contain one.
    let (credentials, host) = remaining.rsplit_once('@')?;
    let (user, password) = credentials.split_once(':').unwrap_or((credentials, ""));

    // The path (`/database`) and the query string are none of our concern.
    let host = host.split(['/', '?']).next()?;
    let (host, port) = match host.rsplit_once(':') {
        Some((h, p)) => (h, p.parse().unwrap_or(default_port)),
        None => (host, default_port),
    };

    if host.is_empty() || user.is_empty() {
        return None;
    }

    Some(Credentials {
        user: percent_decode(user),
        password: percent_decode(password),
        host: host.to_string(),
        port,
    })
}

/// Minimal percent decoding, enough for a URL credential.
fn percent_decode(s: &str) -> String {
    let o = s.as_bytes();
    let mut out = Vec::with_capacity(o.len());
    let mut i = 0;

    while i < o.len() {
        // On the bytes, never `&s[..]`: a `%` followed by a multi-byte character cut
        // the str inside it, and the decoding panicked.
        if o[i] == b'%' && i + 2 < o.len() {
            let hex = std::str::from_utf8(&o[i + 1..i + 3]).ok();
            if let Some(v) = hex.and_then(|h| u8::from_str_radix(h, 16).ok()) {
                out.push(v);
                i += 3;
                continue;
            }
        }
        out.push(o[i]);
        i += 1;
    }
    String::from_utf8_lossy(&out).into_owned()
}

