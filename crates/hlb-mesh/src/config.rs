//! Addressing and WireGuard configuration generation.
//!
//! The mesh is **full**: every node knows every other. On a three to ten machine
//! homelab that is the right choice - no single chokepoint, and a node going down
//! isolates nobody. A star topology would need less configuration, but would make the
//! hub a single point of failure for all inter-node traffic, which is exactly what
//! this is meant to avoid.

use std::collections::BTreeMap;
use std::net::Ipv4Addr;

use crate::keys::KeyPair;
use crate::{Error, Result};

/// A node of the mesh.
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub struct Peer {
    pub name: String,
    /// Address within the mesh network.
    pub mesh_ip: Ipv4Addr,
    pub public_key: String,
    /// Reachable address for establishing the tunnel. Absent for a node behind NAT:
    /// it will have to initiate the connection itself.
    pub endpoint: Option<String>,
    /// How Homelabus reaches the node to push its configuration: `user@host:port`,
    /// each part optional. Absent on the node Homelabus runs on, and on nodes added by
    /// hand — those are reconfigured locally or by hand.
    ///
    /// Every peer's configuration names every other peer: adding a node is only done
    /// once each existing node has been told about it.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub ssh: Option<String>,
}

/// The mesh as a whole.
#[derive(Debug, Clone)]
pub struct MeshConfig {
    /// The mesh private network, a /24. `10.42.0.0` by default.
    network: [u8; 3],
    port: u16,
    peers: BTreeMap<String, Peer>,
}

impl Default for MeshConfig {
    fn default() -> Self {
        Self {
            // 10.42.0.0/24 is unlikely to collide with the home network (usually
            // 192.168.1.0/24) or with Docker's own ranges (172.17-31.0.0/16, and
            // 10.0.0.0/24 for the ingress overlay).
            network: [10, 42, 0],
            port: 51820,
            peers: BTreeMap::new(),
        }
    }
}

impl MeshConfig {
    pub fn new(network: [u8; 3], port: u16) -> Self {
        Self {
            network,
            port,
            peers: BTreeMap::new(),
        }
    }

    pub fn port(&self) -> u16 {
        self.port
    }

    pub fn peers(&self) -> impl Iterator<Item = &Peer> {
        self.peers.values()
    }

    pub fn get(&self, name: &str) -> Option<&Peer> {
        self.peers.get(name)
    }

    /// The mesh network in CIDR notation.
    pub fn cidr(&self) -> String {
        format!(
            "{}.{}.{}.0/24",
            self.network[0], self.network[1], self.network[2]
        )
    }

    /// Adds a node, giving it the first free address.
    ///
    /// Allocation is **deterministic and stable**: a node keeps its address as long as
    /// it is in the mesh. An address that shifted as nodes were added would break the
    /// configurations already deployed on every other node.
    pub fn add_node(
        &mut self,
        name: &str,
        public_key: &str,
        endpoint: Option<String>,
    ) -> Result<Peer> {
        if self.peers.contains_key(name) {
            return Err(Error::DuplicateNode(name.to_string()));
        }

        // .1 is reserved by convention (gateway), .0 and .255 by the protocol. That
        // leaves .2 through .254.
        let taken: std::collections::BTreeSet<u8> =
            self.peers.values().map(|p| p.mesh_ip.octets()[3]).collect();

        let free = (2u8..=254)
            .find(|o| !taken.contains(o))
            .ok_or_else(|| Error::AddressPoolExhausted(253, self.cidr()))?;

        let peer = Peer {
            name: name.to_string(),
            mesh_ip: Ipv4Addr::new(self.network[0], self.network[1], self.network[2], free),
            public_key: public_key.to_string(),
            endpoint,
            ssh: None,
        };

        self.peers.insert(name.to_string(), peer.clone());
        Ok(peer)
    }

    /// The `wg-quick` configuration for a given node.
    ///
    /// The private key is passed separately: it lives in the vault and must never
    /// travel through the structure describing the mesh.
    pub fn render_for(&self, node: &str, private_key: &str) -> Option<String> {
        let me = self.peers.get(node)?;
        let mut s = String::new();

        s.push_str("# Generated by Homelabus - do not edit by hand.\n");
        s.push_str(&format!("# node: {}\n\n", me.name));
        s.push_str("[Interface]\n");
        s.push_str(&format!("PrivateKey = {private_key}\n"));
        s.push_str(&format!("Address = {}/24\n", me.mesh_ip));
        // The firewall comes up with the interface: Swarm's ports are closed outside
        // the tunnel from the moment the tunnel exists.
        s.push_str(&format!("PostUp = nft -f {FIREWALL_PATH}\n"));

        // A node with no endpoint is behind NAT: it has nothing to listen for, it
        // will initiate the connections.
        if me.endpoint.is_some() {
            s.push_str(&format!("ListenPort = {}\n", self.port));
        }

        for p in self.peers.values() {
            if p.name == node {
                continue;
            }
            s.push_str(&format!("\n[Peer]\n# {}\n", p.name));
            s.push_str(&format!("PublicKey = {}\n", p.public_key));
            // /32: each peer routes only its own address. A /24 here would make the
            // last declared peer swallow all the mesh traffic.
            s.push_str(&format!("AllowedIPs = {}/32\n", p.mesh_ip));

            if let Some(e) = &p.endpoint {
                s.push_str(&format!("Endpoint = {e}:{}\n", self.port));
            }
            // Keeps the NAT mapping open. Without it, a node behind a home router
            // becomes unreachable after a few minutes of silence.
            s.push_str("PersistentKeepalive = 25\n");
        }

        Some(s)
    }

    /// Rebuilds a mesh from peers that already have addresses.
    ///
    /// 🔴 Addresses are **taken as they are**, never recomputed: a node whose address
    /// changed on reload would invalidate the configurations deployed on every other
    /// machine.
    pub fn from_peers(network: [u8; 3], port: u16, peers: Vec<Peer>) -> Self {
        Self {
            network,
            port,
            peers: peers.into_iter().map(|p| (p.name.clone(), p)).collect(),
        }
    }

    /// The peer other than `name` already recorded at `host`, by its endpoint or by the
    /// SSH address configurations are pushed to.
    ///
    /// 🔴 Two peers at one address are one machine with two configurations: every push
    /// writes both there, in turn, and the last one wins — a new node took the tunnel of
    /// a dead peer recorded at its address (found on the lab, 2026-10-29).
    pub fn held_by(&self, host: &str, name: &str) -> Option<&Peer> {
        let host = host_of(host);
        self.peers.values().find(|p| {
            p.name != name
                && [p.endpoint.as_deref(), p.ssh.as_deref()]
                    .into_iter()
                    .flatten()
                    .any(|a| host_of(a) == host)
        })
    }

    /// Takes a node out. Its address is free for the next node: the others drop the
    /// node from their configurations at the next push.
    pub fn remove_node(&mut self, name: &str) -> Option<Peer> {
        self.peers.remove(name)
    }

    /// The mesh addresses of every node - what Swarm must listen on.
    pub fn advertise_addr_for(&self, node: &str) -> Option<String> {
        self.peers.get(node).map(|p| p.mesh_ip.to_string())
    }
}

/// The host in `user@host:port`, `host:port` or `[v6]:port`, each part optional.
pub fn host_of(address: &str) -> &str {
    let rest = address.rsplit_once('@').map_or(address, |(_, h)| h);
    if let Some(v6) = rest.strip_prefix('[') {
        return v6.split_once(']').map_or(v6, |(h, _)| h);
    }
    // Two colons or more: a bare IPv6 address, with no port.
    match rest.split_once(':') {
        Some((h, p)) if !p.contains(':') => h,
        _ => rest,
    }
}

/// Where the node's WireGuard configuration lives.
pub const CONFIG_PATH: &str = "/etc/wireguard/hlb0.conf";

/// Where the firewall rules the interface loads live.
pub const FIREWALL_PATH: &str = "/etc/wireguard/hlb0.nft";

/// The rules that keep Swarm's ports on the mesh.
///
/// 🔴 2377 is the cluster's control API; 4789 is VXLAN, which has NO authentication —
/// anyone who can send it a packet can inject traffic into every overlay network.
/// Advertising on the mesh address tells the nodes where to talk; it does not stop the
/// kernel from accepting VXLAN on every interface. These rules do.
///
/// `policy accept`, and only these four ports: nothing else on the machine changes, so
/// a mistake here cannot lock anyone out of SSH. Priority -10 runs it before Docker's
/// own rules. The `table` / `delete table` pair makes loading it twice harmless.
pub fn firewall_rules(interface: &str) -> String {
    format!(
        "# Generated by Homelabus - do not edit by hand.\n\
         # Swarm's ports answer on the mesh only.\n\
         table inet hlb_swarm\n\
         delete table inet hlb_swarm\n\
         table inet hlb_swarm {{\n\
         \tchain input {{\n\
         \t\ttype filter hook input priority -10; policy accept;\n\
         \t\tiifname \"{interface}\" accept\n\
         \t\tiifname \"lo\" accept\n\
         \t\ttcp dport {{ 2377, 7946 }} drop\n\
         \t\tudp dport {{ 7946, 4789 }} drop\n\
         \t}}\n\
         }}\n"
    )
}

/// The mesh interface's name, and the `wg-quick@` unit that carries it.
pub const INTERFACE: &str = "hlb0";

/// Creates a node with a fresh key pair.
pub fn provision_node(
    mesh: &mut MeshConfig,
    name: &str,
    endpoint: Option<String>,
) -> Result<(Peer, KeyPair)> {
    let kp = KeyPair::generate();
    let peer = mesh.add_node(name, &kp.public, endpoint)?;
    Ok((peer, kp))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn mesh_with(names: &[&str]) -> MeshConfig {
        let mut m = MeshConfig::default();
        for n in names {
            m.add_node(n, &format!("key-{n}"), Some(format!("{n}.example.fr")))
                .expect("ajout");
        }
        m
    }

    #[test]
    fn addresses_start_at_two() {
        // .0 and .255 are reserved by the protocol, .1 by convention.
        let m = mesh_with(&["n1", "n2"]);
        assert_eq!(
            m.get("n1").expect("n1").mesh_ip,
            Ipv4Addr::new(10, 42, 0, 2)
        );
        assert_eq!(
            m.get("n2").expect("n2").mesh_ip,
            Ipv4Addr::new(10, 42, 0, 3)
        );
    }

    #[test]
    fn an_address_is_stable_across_additions() {
        // 🔴 An address that shifted as nodes were added would break every
        // configuration already deployed on the other nodes.
        let mut m = mesh_with(&["n1", "n2"]);
        let before = m.get("n1").expect("n1").mesh_ip;

        m.add_node("n3", "key-n3", None).expect("ajout");
        assert_eq!(m.get("n1").expect("n1").mesh_ip, before);
    }

    #[test]
    fn a_duplicate_node_is_refused() {
        let mut m = mesh_with(&["n1"]);
        assert!(matches!(
            m.add_node("n1", "other-key", None),
            Err(Error::DuplicateNode(_))
        ));
    }

    #[test]
    fn the_default_network_avoids_common_collisions() {
        // 192.168.1.0/24 is the most common home network, and Docker uses
        // 172.17-31.0.0/16 plus 10.0.0.0/24 for the ingress overlay.
        let c = MeshConfig::default().cidr();
        assert_eq!(c, "10.42.0.0/24");
        assert!(!c.starts_with("192.168."));
        assert!(!c.starts_with("172."));
    }

    #[test]
    fn a_configuration_lists_every_other_peer() {
        let m = mesh_with(&["n1", "n2", "n3"]);
        let c = m.render_for("n1", "MY-PRIVATE-KEY").expect("config");

        assert!(c.contains("PrivateKey = MY-PRIVATE-KEY"));
        assert!(c.contains("Address = 10.42.0.2/24"));
        // The other two, and not itself.
        assert_eq!(c.matches("[Peer]").count(), 2, "{c}");
        assert!(c.contains("key-n2"));
        assert!(c.contains("key-n3"));
        assert!(!c.contains("key-n1"), "a node must not be its own peer");
    }

    #[test]
    fn each_peer_routes_only_its_own_address() {
        // 🔴 A /24 here would make the last declared peer swallow all mesh traffic -
        // the others would become unreachable with no visible error.
        let m = mesh_with(&["n1", "n2"]);
        let c = m.render_for("n1", "x").expect("config");

        assert!(c.contains("AllowedIPs = 10.42.0.3/32"), "{c}");
        assert!(!c.contains("AllowedIPs = 10.42.0.0/24"));
    }

    #[test]
    fn a_natted_node_does_not_listen_but_keeps_alive() {
        let mut m = MeshConfig::default();
        m.add_node("public", "key-pub", Some("public.example.fr".into()))
            .expect("ajout");
        m.add_node("derriere-nat", "key-nat", None).expect("ajout");

        let c = m.render_for("derriere-nat", "x").expect("config");
        assert!(
            !c.contains("ListenPort"),
            "a NATed node has nothing to listen for:\n{c}"
        );
        // But it must keep the NAT mapping open, or it becomes unreachable after a
        // few minutes of silence.
        assert!(c.contains("PersistentKeepalive = 25"));
        assert!(c.contains("Endpoint = public.example.fr:51820"));
    }

    #[test]
    fn a_public_node_listens() {
        let m = mesh_with(&["n1"]);
        assert!(m
            .render_for("n1", "x")
            .expect("config")
            .contains("ListenPort = 51820"));
    }

    #[test]
    fn an_unknown_node_has_no_configuration() {
        assert!(mesh_with(&["n1"]).render_for("unknown", "x").is_none());
    }

    #[test]
    fn the_firewall_comes_up_with_the_interface() {
        let c = mesh_with(&["n1"]).render_for("n1", "x").expect("config");
        assert!(c.contains(&format!("PostUp = nft -f {FIREWALL_PATH}")));
    }

    #[test]
    fn swarm_ports_are_dropped_outside_the_mesh_and_nothing_else_is() {
        let r = firewall_rules(INTERFACE);
        assert!(r.contains("iifname \"hlb0\" accept"));
        assert!(r.contains("tcp dport { 2377, 7946 } drop"));
        assert!(r.contains("udp dport { 7946, 4789 } drop"));
        // Accept by default: a rule set that dropped everything else would cut SSH.
        assert!(r.contains("policy accept"));
        assert!(!r.contains("dport 22"));
    }

    #[test]
    fn a_peer_without_ssh_reads_back_from_older_json() {
        // Topologies stored before `ssh` existed must still load.
        let old = r#"[{"name":"n1","mesh_ip":"10.42.0.2","public_key":"k","endpoint":null}]"#;
        let peers: Vec<Peer> = serde_json::from_str(old).expect("parsable");
        assert_eq!(peers[0].ssh, None);
    }

    #[test]
    fn the_generated_file_warns_against_hand_editing() {
        let c = mesh_with(&["n1"]).render_for("n1", "x").expect("config");
        assert!(c.contains("do not edit by hand"));
    }

    #[test]
    fn swarm_advertises_on_the_mesh_address() {
        // 🔴 This is the whole point of the mesh: Swarm must not listen on the
        // public IP, where its 2377/7946/4789 ports would be exposed.
        let m = mesh_with(&["n1"]);
        assert_eq!(m.advertise_addr_for("n1").as_deref(), Some("10.42.0.2"));
    }

    #[test]
    fn provisioning_generates_a_usable_pair() {
        let mut m = MeshConfig::default();
        let (peer, kp) = provision_node(&mut m, "n1", None).expect("provisionnement");

        assert_eq!(peer.public_key, kp.public);
        // The configuration must be rendered with the matching private key.
        let c = m.render_for("n1", &kp.private).expect("config");
        assert!(c.contains(&kp.private));
        // And above all NOT the private key inside the shared mesh structure.
        assert!(!peer.public_key.contains(&kp.private));
    }

    #[test]
    fn the_pool_is_bounded() {
        let mut m = MeshConfig::default();
        for i in 0..253 {
            m.add_node(&format!("n{i}"), "k", None).expect("ajout");
        }
        assert!(matches!(
            m.add_node("one-too-many", "k", None),
            Err(Error::AddressPoolExhausted(..))
        ));
    }
}

#[cfg(test)]
mod address_tests {
    use super::*;

    fn lab() -> MeshConfig {
        let mut m = MeshConfig::default();
        m.add_node("arch1", "k1", Some("10.77.0.13".into()))
            .expect("arch1");
        m.add_node("deb2", "k2", None).expect("deb2");
        let mut peers: Vec<_> = m.peers().cloned().collect();
        for p in &mut peers {
            p.ssh = Some(format!(
                "root@10.77.0.{}:22",
                if p.name == "deb2" { 12 } else { 13 }
            ));
        }
        MeshConfig::from_peers([10, 42, 0], 51820, peers)
    }

    #[test]
    fn an_address_another_peer_holds_is_named() {
        let m = lab();
        // A fresh machine given a dead peer's address.
        assert_eq!(
            m.held_by("10.77.0.13", "bare1").map(|p| p.name.as_str()),
            Some("arch1")
        );
        // Held through its SSH address alone: deb2 has no endpoint.
        assert_eq!(
            m.held_by("10.77.0.12", "bare1").map(|p| p.name.as_str()),
            Some("deb2")
        );
        // A node's own address is its own.
        assert!(m.held_by("10.77.0.13", "arch1").is_none());
        assert!(m.held_by("10.77.0.17", "bare2").is_none());
    }

    #[test]
    fn the_host_is_read_out_of_every_address_shape() {
        for (address, host) in [
            ("10.77.0.13", "10.77.0.13"),
            ("root@10.77.0.13", "10.77.0.13"),
            ("root@10.77.0.13:2222", "10.77.0.13"),
            ("deb1.lan:22", "deb1.lan"),
            ("[fd00::13]:22", "fd00::13"),
            ("root@[fd00::13]", "fd00::13"),
            ("fd00::13", "fd00::13"),
        ] {
            assert_eq!(host_of(address), host, "{address}");
        }
    }

    #[test]
    fn a_removed_node_leaves_every_configuration() {
        let mut m = lab();
        assert!(m.remove_node("arch1").is_some());
        assert!(m.remove_node("arch1").is_none());
        let conf = m.render_for("deb2", "private").expect("deb2");
        assert!(!conf.contains("arch1") && !conf.contains("k1"), "{conf}");
        assert!(m.held_by("10.77.0.13", "bare1").is_none());
    }
}

#[cfg(test)]
mod persistence_tests {
    use super::*;

    #[test]
    fn reloading_preserves_every_address() {
        // 🔴 Recomputing addresses on reload would reassign them alphabetically,
        // invalidating in one go every configuration deployed elsewhere - without a
        // single error message.
        let mut m = MeshConfig::default();
        m.add_node("zeta", "k1", None).expect("ajout");
        m.add_node("alpha", "k2", None).expect("ajout");

        let before: Vec<_> = m.peers().map(|p| (p.name.clone(), p.mesh_ip)).collect();

        let reload = MeshConfig::from_peers([10, 42, 0], 51820, m.peers().cloned().collect());
        let after: Vec<_> = reload
            .peers()
            .map(|p| (p.name.clone(), p.mesh_ip))
            .collect();

        assert_eq!(before, after);
        // `zeta`, added first, keeps .2 even though it sorts after `alpha`.
        assert_eq!(
            reload.get("zeta").expect("zeta").mesh_ip,
            std::net::Ipv4Addr::new(10, 42, 0, 2)
        );
    }

    #[test]
    fn a_new_node_takes_the_first_free_address_after_reload() {
        let m = MeshConfig::from_peers(
            [10, 42, 0],
            51820,
            vec![Peer {
                name: "n1".into(),
                mesh_ip: std::net::Ipv4Addr::new(10, 42, 0, 5),
                public_key: "k".into(),
                endpoint: None,
                ssh: None,
            }],
        );
        let mut m = m;
        let p = m.add_node("n2", "k2", None).expect("ajout");
        // .2 is free: gaps left by a removal get reused.
        assert_eq!(p.mesh_ip, std::net::Ipv4Addr::new(10, 42, 0, 2));
    }

    #[test]
    fn peers_survive_a_json_round_trip() {
        let p = Peer {
            name: "n1".into(),
            mesh_ip: std::net::Ipv4Addr::new(10, 42, 0, 2),
            public_key: "key".into(),
            endpoint: Some("n1.example.fr".into()),
            ssh: Some("root@n1.example.fr:2222".into()),
        };
        let j = serde_json::to_string(&p).expect("serialisable");
        assert_eq!(serde_json::from_str::<Peer>(&j).expect("analysable"), p);
    }
}
