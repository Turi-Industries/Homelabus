//! The link between the house and a site of its own: a rented VPS.
//!
//! 🔴 **The site is never a peer of the mesh.** The mesh carries Swarm, and a machine on
//! it reaches 2377 — the cluster's control API, through which a manager reads every
//! secret. The site sits on an interface of its own, in a network of its own, and each
//! house node's firewall lets it reach the ports the front door relays and nothing else.
//!
//! A star, unlike the mesh: the VPS is the hub, and every house node opens its own tunnel
//! to it, because the house is behind NAT or a CGNAT and the VPS is the one with a public
//! address. Members never talk to one another through it — they have the mesh for that.

use std::net::Ipv4Addr;

use crate::{Error, Result};

/// The interface on both ends, and the `wg-quick@` unit carrying it.
pub const INTERFACE: &str = "hlb-site";

/// Where each end's WireGuard configuration lives.
pub const CONFIG_PATH: &str = "/etc/wireguard/hlb-site.conf";

/// Where the firewall rules the interface loads live.
pub const FIREWALL_PATH: &str = "/etc/wireguard/hlb-site.nft";

/// The service name of the unit files carrying the link — never the mesh's, whose
/// ordering before Docker they would overwrite.
pub const UNIT: &str = "hlb-site";

/// Where the VPS listens. Not the mesh's 51820: one number, one tunnel, on a capture.
pub const PORT: u16 = 51821;

/// The ports the site may open at home: what the front door relays, nothing else.
///
/// 443 is not one of them: HTTPS is relayed to Caddy's relay port, where nothing the
/// site sends is taken for the house. Held equal to `hlb_ingress`'s by `hlb-cli`.
pub const HOUSE_PORTS: [u16; 2] = [80, 10443];

/// `10.43.0.0/24`, beside the mesh's `10.42.0.0/24` and clear of Docker's ranges.
const NETWORK: [u8; 3] = [10, 43, 0];

/// The VPS's address on the link.
pub const HUB: Ipv4Addr = Ipv4Addr::new(NETWORK[0], NETWORK[1], NETWORK[2], 1);

/// A house node on the link.
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Member {
    pub name: String,
    pub address: Ipv4Addr,
    pub public_key: String,
}

/// The site, and the house nodes linked to it.
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Site {
    /// The site's name, as the CLI and the interface say it: `vps`.
    pub name: String,
    /// The VPS's public address, without a port: where every house node's tunnel goes.
    pub endpoint: String,
    /// How Homelabus reaches it to push its configuration: `user@host:port`.
    pub ssh: String,
    pub public_key: String,
    /// Read off the machine when it was added: what the lifeboat's selection must fit.
    pub memory_mb: Option<u64>,
    pub free_disk_mb: Option<u64>,
    /// Kept sorted by name, so two renderings of one site are byte for byte the same.
    #[serde(default)]
    pub members: Vec<Member>,
}

impl Site {
    pub fn cidr() -> String {
        format!("{}.{}.{}.0/24", NETWORK[0], NETWORK[1], NETWORK[2])
    }

    pub fn member(&self, name: &str) -> Option<&Member> {
        self.members.iter().find(|m| m.name == name)
    }

    /// Links a house node, giving it the first free address, or returns it as it is.
    ///
    /// Allocation is stable, as in the mesh: an address that moved would break the
    /// configuration already on the VPS until the next push.
    pub fn add_member(&mut self, name: &str, public_key: &str) -> Result<Member> {
        if let Some(m) = self.member(name) {
            return Ok(m.clone());
        }
        let taken: std::collections::BTreeSet<u8> =
            self.members.iter().map(|m| m.address.octets()[3]).collect();
        // .1 is the hub, .0 and .255 the protocol's.
        let free = (2u8..=254)
            .find(|o| !taken.contains(o))
            .ok_or_else(|| Error::AddressPoolExhausted(253, Self::cidr()))?;
        let member = Member {
            name: name.to_string(),
            address: Ipv4Addr::new(NETWORK[0], NETWORK[1], NETWORK[2], free),
            public_key: public_key.to_string(),
        };
        self.members.push(member.clone());
        self.members.sort_by(|a, b| a.name.cmp(&b.name));
        Ok(member)
    }

    /// Unlinks a house node. The VPS forgets it at the next push.
    pub fn remove_member(&mut self, name: &str) -> Option<Member> {
        let i = self.members.iter().position(|m| m.name == name)?;
        Some(self.members.remove(i))
    }

    /// The VPS's `wg-quick` configuration. The private key comes from the vault, never
    /// through the structure describing the site.
    pub fn render_hub(&self, private_key: &str) -> String {
        let mut s = String::new();
        s.push_str("# Generated by Homelabus - do not edit by hand.\n");
        s.push_str(&format!("# site: {}\n\n", self.name));
        s.push_str("[Interface]\n");
        s.push_str(&format!("PrivateKey = {private_key}\n"));
        s.push_str(&format!("Address = {HUB}/24\n"));
        s.push_str(&format!("ListenPort = {PORT}\n"));
        s.push_str(&format!("PostUp = nft -f {FIREWALL_PATH}\n"));
        for m in &self.members {
            s.push_str(&format!("\n[Peer]\n# {}\n", m.name));
            s.push_str(&format!("PublicKey = {}\n", m.public_key));
            // No endpoint: the member is behind NAT, its own keepalive opens the way.
            s.push_str(&format!("AllowedIPs = {}/32\n", m.address));
        }
        s
    }

    /// A house node's configuration. `None` for a node not linked.
    pub fn render_member(&self, node: &str, private_key: &str) -> Option<String> {
        let me = self.member(node)?;
        let mut s = String::new();
        s.push_str("# Generated by Homelabus - do not edit by hand.\n");
        s.push_str(&format!("# site: {}, node: {}\n\n", self.name, me.name));
        s.push_str("[Interface]\n");
        s.push_str(&format!("PrivateKey = {private_key}\n"));
        // /32: no route to the other members through the hub.
        s.push_str(&format!("Address = {}/32\n", me.address));
        s.push_str(&format!("PostUp = nft -f {FIREWALL_PATH}\n"));
        s.push_str(&format!("\n[Peer]\n# {}\n", self.name));
        s.push_str(&format!("PublicKey = {}\n", self.public_key));
        s.push_str(&format!("AllowedIPs = {HUB}/32\n"));
        s.push_str(&format!(
            "Endpoint = {}:{PORT}\n",
            bracketed(&self.endpoint)
        ));
        // The house opens the tunnel and keeps its NAT mapping open: the VPS has no way
        // to reach a house that went quiet.
        s.push_str("PersistentKeepalive = 25\n");
        Some(s)
    }
}

/// An IPv6 literal in brackets, so the port that follows is not read as part of it.
fn bracketed(host: &str) -> String {
    if host.contains(':') && !host.starts_with('[') {
        format!("[{host}]")
    } else {
        host.to_string()
    }
}

/// A house node's rules: from the site, the front door's ports and a ping, nothing else.
///
/// 🔴 **At prerouting, before Docker's DNAT.** Caddy publishes 80 and 443 in host mode,
/// which Docker implements as a DNAT to the container: that traffic never crosses the
/// `input` hook, so rules there would let the VPS reach every published port while
/// looking closed. Priority -150 runs after conntrack (-200) and before DNAT (-100).
///
/// `policy accept` for everything not arriving on the link: nothing else on the machine
/// changes, so a mistake here cannot lock anyone out.
pub fn member_firewall() -> String {
    let ports = HOUSE_PORTS.map(|p| p.to_string()).join(", ");
    format!(
        "# Generated by Homelabus - do not edit by hand.\n\
         # The site reaches the front door's ports at home, and nothing else.\n\
         table inet hlb_site\n\
         delete table inet hlb_site\n\
         table inet hlb_site {{\n\
         \tchain prerouting {{\n\
         \t\ttype filter hook prerouting priority -150; policy accept;\n\
         \t\tiifname != \"{INTERFACE}\" accept\n\
         \t\tct state established,related accept\n\
         \t\tip saddr {HUB} tcp dport {{ {ports} }} accept\n\
         \t\tip saddr {HUB} icmp type echo-request accept\n\
         \t\tdrop\n\
         \t}}\n\
         }}\n"
    )
}

/// The VPS's rules: Swarm's ports closed to everything but itself, and the link closed
/// to what the house opens on it.
///
/// 🔴 The VPS runs a Swarm of its own, one node. Its ports answer on every interface
/// whatever the advertised address — a public machine whose 4789 (VXLAN, no
/// authentication) is open lets anyone inject traffic into its overlays. Its own
/// traffic to itself crosses `lo`, which stays open.
///
/// The house's nodes open nothing new on the link yet: what answers them (the tunnel's
/// pings, the replies to what the VPS relays) is established traffic.
pub fn hub_firewall() -> String {
    format!(
        "# Generated by Homelabus - do not edit by hand.\n\
         # The site's own Swarm answers to itself only; the house opens nothing on it.\n\
         table inet hlb_site\n\
         delete table inet hlb_site\n\
         table inet hlb_site {{\n\
         \tchain input {{\n\
         \t\ttype filter hook input priority -10; policy accept;\n\
         \t\tiifname \"lo\" accept\n\
         \t\ttcp dport {{ 2377, 7946 }} drop\n\
         \t\tudp dport {{ 7946, 4789 }} drop\n\
         \t}}\n\
         \tchain prerouting {{\n\
         \t\ttype filter hook prerouting priority -150; policy accept;\n\
         \t\tiifname != \"{INTERFACE}\" accept\n\
         \t\tct state established,related accept\n\
         \t\ticmp type echo-request accept\n\
         \t\tdrop\n\
         \t}}\n\
         }}\n"
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn site() -> Site {
        Site {
            name: "vps".into(),
            endpoint: "203.0.113.7".into(),
            ssh: "root@203.0.113.7".into(),
            public_key: "HUB-PUBLIC".into(),
            memory_mb: Some(4096),
            free_disk_mb: Some(40_960),
            members: Vec::new(),
        }
    }

    #[test]
    fn members_take_addresses_from_two_and_keep_them() {
        let mut s = site();
        let b = s.add_member("deb2", "k2").expect("deb2");
        let a = s.add_member("deb1", "k1").expect("deb1");
        assert_eq!(b.address, Ipv4Addr::new(10, 43, 0, 2));
        assert_eq!(a.address, Ipv4Addr::new(10, 43, 0, 3));
        s.remove_member("deb2");
        s.add_member("deb3", "k3").expect("deb3");
        assert_eq!(
            s.member("deb1").expect("deb1").address,
            Ipv4Addr::new(10, 43, 0, 3),
            "an address that moved would break the VPS's configuration"
        );
    }

    #[test]
    fn adding_a_linked_member_again_keeps_its_key() {
        let mut s = site();
        s.add_member("deb1", "first").expect("deb1");
        let again = s.add_member("deb1", "second").expect("deb1");
        assert_eq!(again.public_key, "first");
        assert_eq!(s.members.len(), 1);
    }

    #[test]
    fn the_site_network_is_not_the_mesh() {
        assert_ne!(Site::cidr(), crate::MeshConfig::default().cidr());
        assert_ne!(INTERFACE, crate::INTERFACE);
        assert_ne!(CONFIG_PATH, crate::CONFIG_PATH);
        assert_ne!(FIREWALL_PATH, crate::FIREWALL_PATH);
        assert_ne!(PORT, crate::MeshConfig::default().port());
    }

    #[test]
    fn a_member_routes_the_hub_alone_and_keeps_its_nat_open() {
        let mut s = site();
        s.add_member("deb1", "k1").expect("deb1");
        let c = s.render_member("deb1", "PRIV").expect("linked");
        assert!(c.contains("Address = 10.43.0.2/32"), "{c}");
        assert!(c.contains("AllowedIPs = 10.43.0.1/32"), "{c}");
        assert!(c.contains("Endpoint = 203.0.113.7:51821"), "{c}");
        assert!(c.contains("PersistentKeepalive = 25"), "{c}");
        assert!(
            !c.contains("ListenPort"),
            "a member behind NAT listens for nothing"
        );
        assert_eq!(c.matches("[Peer]").count(), 1);
        assert!(s.render_member("deb9", "PRIV").is_none());
    }

    #[test]
    fn an_ipv6_endpoint_is_bracketed() {
        let mut s = site();
        s.endpoint = "2001:db8::7".into();
        s.add_member("deb1", "k1").expect("deb1");
        let c = s.render_member("deb1", "PRIV").expect("linked");
        assert!(c.contains("Endpoint = [2001:db8::7]:51821"), "{c}");
    }

    #[test]
    fn the_hub_lists_every_member_by_its_own_address() {
        let mut s = site();
        s.add_member("deb1", "k1").expect("deb1");
        s.add_member("deb2", "k2").expect("deb2");
        let c = s.render_hub("PRIV");
        assert!(c.contains("ListenPort = 51821"), "{c}");
        assert!(c.contains("AllowedIPs = 10.43.0.2/32"), "{c}");
        assert!(c.contains("AllowedIPs = 10.43.0.3/32"), "{c}");
        assert!(!c.contains("Endpoint"), "members are behind NAT: {c}");
    }

    #[test]
    fn both_ends_load_their_firewall_with_the_interface() {
        let mut s = site();
        s.add_member("deb1", "k1").expect("deb1");
        let load = format!("PostUp = nft -f {FIREWALL_PATH}");
        assert!(s.render_hub("PRIV").contains(&load));
        assert!(s
            .render_member("deb1", "PRIV")
            .expect("linked")
            .contains(&load));
    }

    #[test]
    fn the_house_filters_the_link_before_dockers_dnat() {
        // 🔴 Docker publishes host-mode ports through a DNAT: an `input` rule never
        // sees that traffic, and every published port would stay open to the VPS.
        let f = member_firewall();
        assert!(f.contains("hook prerouting priority -150"), "{f}");
        assert!(!f.contains("hook input"), "{f}");
        assert!(
            f.contains("ip saddr 10.43.0.1 tcp dport { 80, 10443 } accept"),
            "{f}"
        );
        assert!(f.trim_end().ends_with("drop\n\t}\n}"), "{f}");
    }

    #[test]
    fn the_house_never_opens_swarms_ports_to_the_site() {
        let f = member_firewall();
        for port in ["2377", "7946", "4789"] {
            assert!(!f.contains(port), "{port} in the house's site rules: {f}");
        }
        assert!(!HOUSE_PORTS.iter().any(|p| [2377, 7946, 4789].contains(p)));
    }

    #[test]
    fn the_vps_closes_its_own_swarm_to_everything_but_itself() {
        let f = hub_firewall();
        assert!(f.contains("iifname \"lo\" accept"), "{f}");
        assert!(f.contains("tcp dport { 2377, 7946 } drop"), "{f}");
        assert!(f.contains("udp dport { 7946, 4789 } drop"), "{f}");
        let lo = f.find("iifname \"lo\" accept").expect("lo");
        let drop = f.find("tcp dport { 2377").expect("drop");
        assert!(lo < drop, "its own traffic to itself first: {f}");
    }

    #[test]
    fn rules_can_be_loaded_twice() {
        for f in [member_firewall(), hub_firewall()] {
            assert!(f.contains("table inet hlb_site\ndelete table inet hlb_site\n"));
        }
    }

    #[test]
    fn a_site_refuses_an_unknown_field() {
        let mut v = serde_json::to_value(site()).expect("json");
        v["memroy_mb"] = 4096.into();
        assert!(serde_json::from_value::<Site>(v).is_err());
    }
}
